"""Render rwa-filer's known issues with the published rules as one shareable Markdown page.

The single source is rwa-filer's packaged publisher-issue register, one per
shipped taxonomy release (``packages/rwa-filer/src/rwa_filer/boe/data/issues/
<release>.json``), with Arelle's counts on each issue's minimal correct return
(``packages/rwa-filer/tests/releases/<release>/oracles/publisher_issues_oracle.json``,
measured by ``packages/rwa-filer/tests/issue_returns.py``). The page is the
write-up to share with the Bank of England; ``rwa-filer rulebook issues
--format markdown`` renders the same text without the counts.

Usage:
    uv run python scripts/generate_publisher_issues.py           # write the page
    uv run python scripts/generate_publisher_issues.py --check   # fail if stale

Exit codes:
    0 = the page was written, or is fresh
    1 = --check: the page does not match a fresh render

The page is generated: never hand-edit it. Edit the register (and re-measure
the oracle when an example changes), then regenerate. Gated by
``tests/contracts/test_docs_freshness.py::test_publisher_issues_page_is_fresh``.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Final

from rwa_filer.boe.issues import load_issues
from rwa_filer.boe.issues_document import render_document
from rwa_filer.release import shipped_releases

REPO_ROOT: Final = Path(__file__).resolve().parent.parent
#: The page, and the one file this script writes.
TARGET_PATH: Final = REPO_ROOT / "docs" / "rwa-filer" / "publisher-issues.md"
#: Where each release's Arelle counts are kept.
ORACLES: Final = REPO_ROOT / "packages" / "rwa-filer" / "tests" / "releases"
ORACLE_FILE: Final = "publisher_issues_oracle.json"

PREAMBLE: Final = """\
<!-- GENERATED by scripts/generate_publisher_issues.py from rwa-filer's publisher-issue
registers (packages/rwa-filer/src/rwa_filer/boe/data/issues/) and the Arelle counts kept
beside its tests. Do not edit by hand: edit the register, then regenerate. -->

!!! note "Not yet published"
    This page is generated and kept up to date, but it is not in the site's navigation
    until its owner signs it off: most issues below are drafts, identified by rwa-filer
    and not yet raised with the Bank of England. To send it, render the same text with
    `rwa-filer rulebook issues --format markdown`.
"""


def render() -> str:
    """The page, from every shipped release's register and its Arelle counts."""
    versions = shipped_releases()
    return render_document(
        [load_issues(version) for version in versions],
        arelle={version: _arelle(version) for version in versions},
        preamble=PREAMBLE,
    )


def main(argv: list[str] | None = None) -> int:
    """Write the page, or with ``--check`` report whether it is stale."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the page is stale")
    args = parser.parse_args(argv)
    content = render()
    if args.check:
        current = TARGET_PATH.read_text(encoding="utf-8") if TARGET_PATH.is_file() else ""
        if current != content:
            sys.stdout.write(
                f"{TARGET_PATH.relative_to(REPO_ROOT)} is stale: run "
                "uv run python scripts/generate_publisher_issues.py\n"
            )
            return 1
        return 0
    TARGET_PATH.parent.mkdir(parents=True, exist_ok=True)
    with TARGET_PATH.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(content)
    sys.stdout.write(f"wrote {TARGET_PATH.relative_to(REPO_ROOT)}\n")
    return 0


def _arelle(version: str) -> dict[str, Any]:
    """Arelle's counts on each issue's example in ``version``, by issue; empty if none kept."""
    path = ORACLES / version / "oracles" / ORACLE_FILE
    if not path.is_file():
        return {}
    returns = json.loads(path.read_text(encoding="utf-8"))["returns"]
    return {issue_id: measured["rules"] for issue_id, measured in returns.items()}


if __name__ == "__main__":
    raise SystemExit(main())
