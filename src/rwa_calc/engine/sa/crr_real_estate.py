"""
CRR real-estate risk weights: the Art. 125 / 126 preferential weights and the
Art. 124(1) weight that applies where their conditions are not met.

Pipeline position:
    CRMProcessor -> RealEstateSplitter -> SACalculator
    (``engine/sa/risk_weights.py::_crr_append_real_estate_branches``, the CRR
    override ladder only, and the CRR Art. 127(3) defaulted-RRE share)

Key responsibilities:
- ``crr_commercial_re_rw_expr`` — Art. 126: 50% on the part of the loan up to
  50% of the property value, only where the exposure is not explicitly
  non-qualifying AND its repayment does not materially depend on the property's
  cash flows (Art. 126(2)(b)); otherwise Art. 124(1).
- ``crr_residential_re_rw_expr`` — Art. 125: 35% on the part up to 80% of the
  property value, the counterparty's unsecured weight above it; an explicitly
  non-qualifying exposure takes Art. 124(1) instead.
- ``crr_art_124_1_rw_expr`` — Art. 124(1): 100% on the part secured up to the
  property value, the counterparty's unsecured weight on any excess.
- ``crr_re_conditions_not_met_expr`` — the explicit non-qualifying attestation.

Two review findings shaped this module:

- **CL-07 / RE-09.** ``is_qualifying_re`` was read only by the Basel 3.1 route,
  so an exposure the firm attested as NOT meeting the Art. 125(2) / 126(2)
  conditions still took 35% / 50%. Under CRR an explicit ``False`` now attests
  that the conditions are not met — limbs (a)-(c), Art. 208 / Art. 229(1), and,
  for UK commercial property, the PRA Credit Risk Part rule 4.1 loss condition
  that applies until 31 December 2026. A null attestation keeps the preferential
  weight: making null non-qualifying is the separate open item P1.292 (operator
  decision; not changed here).
- **RE-17 (= P1.263).** The Art. 126 50% was granted when ``has_income_cover``
  was True. That column is "materially dependent on the cash flows generated by
  the property" (it is collateral ``is_income_producing``, the same flag Basel
  3.1 reads for Art. 124E), and Art. 126(2)(b) grants the preferential weight
  only where repayment does NOT so depend. The gate was inverted: owner-occupied
  commercial property took 100% and investment property 50%. The Art. 126(3)
  derogation from limb (b) needs a competent-authority loss-rate determination
  and is not applied.

Rule text (UK CRR as onshored, verbatim):
- Art. 124(1): "An exposure or any part of an exposure fully secured by mortgage
  on immovable property shall be assigned a risk weight of 100 %, where the
  conditions set out in Article 125 or 126 are not met, except for any part of
  the exposure which is assigned to another exposure class. The part of the
  exposure that exceeds the mortgage value of the immovable property shall be
  assigned the risk weight applicable to the unsecured exposures of the
  counterparty involved. The part of an exposure that is treated as fully
  secured by immovable property shall not be greater than the pledged amount of
  the market value ..."
- Art. 126(2): "Institutions shall consider an exposure or any part of an
  exposure as fully and completely secured for the purposes of paragraph 1 only
  if the following conditions are met: ... (b) the risk of the borrower shall
  not materially depend upon the performance of the underlying property or
  project, but on the underlying capacity of the borrower to repay the debt from
  other sources, and as a consequence, the repayment of the facility shall not
  materially depend on any cash flow generated by the underlying property
  serving as collateral; (c) the requirements set out in Article 208 and the
  valuation rules set out in Article 229(1) are met; (d) the 50 % risk weight
  ... shall be assigned to the part of the loan that does not exceed 50 % of the
  market value of the property".
- Art. 125(2)(d): "the part of the loan to which the 35 % risk weight is
  assigned does not exceed 80 % of the market value of the property".
- PRA Rulebook, CRR Firms, Credit Risk Part, rule 4.1 (deleted by PS1/26 from
  1 January 2027): "a firm may treat exposures as fully and completely secured
  by mortgages on commercial immovable property located in the UK in accordance
  with Article 126 of the CRR only where annual average losses stemming from
  lending secured by mortgages on commercial property located in the UK did not
  exceed 0.5% of risk-weighted exposure amounts over a representative period."

Extracted from ``risk_weights.py``, which sits at the ``max_engine_module_loc``
ratchet.

References:
- CRR Art. 124(1), 125(1)-(2), 126(1)-(2), 127(3)
- PRA Rulebook, Credit Risk Part, rule 4.1 (to 31 December 2026)
"""

from __future__ import annotations

import logging
from datetime import date

import polars as pl
from watchfire import cites

from rwa_calc.domain.enums import CQS
from rwa_calc.engine.sa.crr_risk_weight_tables import (
    COMMERCIAL_RE_PARAMS,
    CORPORATE_RISK_WEIGHTS,
    RESIDENTIAL_MORTGAGE_PARAMS,
)
from rwa_calc.engine.sa.re_residual_rw import crr_art_124_1_unsecured_cp_rw_expr
from rwa_calc.engine.sa.sovereign_derived import cqs_table_lookup_expr
from rwa_calc.rulebook.compile import scalar_value
from rwa_calc.rulebook.resolve import resolve

logger = logging.getLogger(__name__)

_CRR_PACK = resolve("crr", date(2026, 1, 1))

# Pack-derived scalars in one dict (the ``risk_weights.py::_SA_CRR_RW`` pattern),
# so the arch check reads none of them as an engine-declared regulatory scalar.
_RW: dict[str, float] = {
    # Art. 125: 35% up to 80% of the property value.
    "resi_ltv_threshold": float(RESIDENTIAL_MORTGAGE_PARAMS["ltv_threshold"]),
    "resi_rw_low": float(RESIDENTIAL_MORTGAGE_PARAMS["rw_low_ltv"]),
    # Art. 126: 50% up to 50% of the property value.
    "cre_ltv_threshold": float(COMMERCIAL_RE_PARAMS["ltv_threshold"]),
    "cre_rw_low": float(COMMERCIAL_RE_PARAMS["rw_low_ltv"]),
    # Art. 124(1): 100% where the Art. 125 / 126 conditions are not met.
    "art_124_1": float(COMMERCIAL_RE_PARAMS["rw_standard"]),
    # Art. 122(2): an unrated corporate takes 100%.
    "corporate_unrated": float(CORPORATE_RISK_WEIGHTS[CQS.UNRATED]),
    # Art. 124(1) third sentence: the secured part is at most the market value.
    "full_value": scalar_value(_CRR_PACK.scalar_param("re_art_124_1_secured_value_cap")),
}


@cites("CRR Art. 126")
def crr_commercial_re_rw_expr() -> pl.Expr:
    """Art. 126 for a commercial real-estate row; Art. 124(1) where it fails.

    The 50% applies to the part of the loan up to 50% of the property value
    (Art. 126(2)(d)); above it the residual takes the Art. 122 corporate weight
    by CQS, looked up directly so it still fires on rows the splitter re-classed
    to ``COMMERCIAL_MORTGAGE`` (P1.181). The preferential limb needs all of:

    - the conditions not attested as unmet (``is_qualifying_re`` not False);
    - ``has_income_cover`` False — the risk does NOT materially depend on the
      property's cash flows (Art. 126(2)(b), review RE-17) — and the row is not
      ADC lending, whose risk depends on the project;
    - an LTV (the hierarchy derives one wherever a valued property is linked).

    Otherwise Art. 124(1): 100% up to the property value and the counterparty's
    unsecured weight above it, or a flat 100% where there is no LTV to size the
    parts (an unvalued property).
    """
    ltv = pl.col("ltv")
    secured_share = pl.min_horizontal(pl.lit(1.0), _RW["cre_ltv_threshold"] / ltv)
    residual_rw = cqs_table_lookup_expr(
        "cqs", CORPORATE_RISK_WEIGHTS, pl.lit(_RW["corporate_unrated"])
    )
    preferential = _RW["cre_rw_low"] * secured_share + residual_rw * (1.0 - secured_share)
    # ADC lending depends on the project by definition — Art. 126(2)(b) names
    # "the performance of the underlying property or project" — so an ``is_adc``
    # row never meets it, whatever its income flag says.
    meets_art_126 = (
        ~crr_re_conditions_not_met_expr()
        & ~pl.col("has_income_cover").fill_null(True)
        & ~pl.col("is_adc").eq_missing(True)
        & ltv.is_not_null()
    )
    return (
        pl.when(meets_art_126)
        .then(preferential)
        .when(ltv.is_not_null())
        .then(crr_art_124_1_rw_expr())
        .otherwise(pl.lit(_RW["art_124_1"]))
    )


@cites("CRR Art. 125")
def crr_residential_re_rw_expr() -> pl.Expr:
    """Art. 125 for a residential real-estate row with an LTV; Art. 124(1) if unmet.

    35% on the part up to 80% of the property value (Art. 125(2)(d)) and the
    obligor's own unsecured weight above it (Art. 124(1) second sentence,
    ``re_residual_rw.py``). An exposure attested as not meeting the Art. 125(2)
    conditions (``is_qualifying_re`` False, review CL-07) takes Art. 124(1).

    The caller gates on a non-null LTV: a residential row without one is a
    mortgage label with no valued property and takes its counterparty class.
    """
    ltv = pl.col("ltv")
    threshold = _RW["resi_ltv_threshold"]
    art_125 = (
        pl.when(ltv <= threshold)
        .then(pl.lit(_RW["resi_rw_low"]))
        .otherwise(
            _RW["resi_rw_low"] * threshold / ltv
            + crr_art_124_1_unsecured_cp_rw_expr() * (ltv - threshold) / ltv
        )
    )
    return (
        pl.when(crr_re_conditions_not_met_expr()).then(crr_art_124_1_rw_expr()).otherwise(art_125)
    )


@cites("CRR Art. 124")
def crr_art_124_1_rw_expr() -> pl.Expr:
    """Art. 124(1): 100% up to the property value, the counterparty's weight above it.

    The part "treated as fully secured by immovable property shall not be
    greater than the pledged amount of the market value", so at an LTV of 1.0
    or less the whole exposure takes 100%; above it the excess takes "the risk
    weight applicable to the unsecured exposures of the counterparty involved"
    (the obligor's own ladder, ``re_residual_rw.py``). Requires a positive LTV.
    """
    secured_share = pl.min_horizontal(pl.lit(1.0), _RW["full_value"] / pl.col("ltv"))
    return _RW["art_124_1"] * secured_share + crr_art_124_1_unsecured_cp_rw_expr() * (
        1.0 - secured_share
    )


def crr_re_conditions_not_met_expr() -> pl.Expr:
    """True only where ``is_qualifying_re`` is explicitly False.

    Under CRR an explicit False attests that the Art. 125(2) / 126(2)
    conditions are not met. Null is "not reported" and keeps the preferential
    treatment — the null default is the open item P1.292, not decided here.
    """
    return pl.col("is_qualifying_re").eq_missing(False)
