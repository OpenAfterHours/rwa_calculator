"""
Report a loan-split real-estate exposure against its two risk weights.

Pipeline position:
    sealed aggregator-exit ledger -> a template's prepared frame
    -> split_risk_weight_parts() -> the risk-weight row axis -> cellspec.execute()
    (used by corep/c07.py::c07_plans; written to be reused by Pillar 3 CR5)

Key responsibilities:
- Turn each ledger row whose REPORTED risk weight is still the engine's recorded
  Art. 124F(1) / 124H(1) two-part weight into two rows — the part up to the 55%
  cap at its secured weight, the rest at its Art. 124L weight — with every
  exposure column split by the share and every RWEA column by its part's share
  of the weight, so the two parts sum to the row.
- Name the columns a template's cells sum (``summed_columns``), so a template
  can scale exactly what it reports and nothing a future cell adds is inherited
  whole by both parts.

THE RULE. PS1/26 Annex II, OF 07.00 rows 0140-0280 (p.94): "Real estate
exposures classified as regulatory real estate (residential or commercial) which
are not materially dependent on the cash flows generated by the property
(Articles 124F and 124H ...) shall be reported in two parts, against the risk
weight applied to the portion up to 55% of the value of the property, and
against the portion above 55% of the value of the property (if applicable)."
Banded on its one blended weight such an exposure matches no published row and
falls to row 0280 "Other risk weights", which ``boe_b0445`` requires empty on the
real-estate sheet.

THE REPORTED WEIGHT. Same page: an exposure under the Art. 123B currency
mismatch multiplier "shall be reported against the risk weight which would have
applied if the currency mismatch multiplier was not applied. However, the RWEA
shall still reflect the currency mismatch multiplier." So a row is recognised on
its pre-multiplier weight, its parts carry the un-multiplied part weights, and
each RWEA part keeps its share of the multiplied RWEA.

WHY THE ENGINE RECORDS THE PARTS. The residual weight is the Art. 124L
counterparty weight, which only the SA dispatcher computes; reporting cannot
re-derive it without restating the dispatcher. The engine writes three carriers
(``engine/sa/b31_risk_weight_tables.py::with_b31_loan_split_parts``), and a row is
split only while its reported weight still EQUALS the recorded blend: a
guaranteed leg at its guarantor's weight, a defaulted leg, any leg a later step
re-weighted keeps carriers that no longer describe it and is left whole.

References:
- PS1/26 Art. 123B, 124F, 124H, 124L; Annex II OF 07.00 rows 0140-0280 (p.94)
"""

from __future__ import annotations

from typing import TYPE_CHECKING

import polars as pl

from rwa_calc.reporting.cellspec import Formula, SafeSum, SideContext, Sum

if TYPE_CHECKING:
    from collections.abc import Collection

    from rwa_calc.reporting.cellspec import TemplateSpec

#: The engine's loan-split carriers (``contracts/edges.py``, CONDITIONAL; absent under CRR).
LOAN_SPLIT_SHARE: str = "sa_loan_split_secured_share"
LOAN_SPLIT_SECURED_RW: str = "sa_loan_split_secured_rw"
LOAN_SPLIT_RESIDUAL_RW: str = "sa_loan_split_residual_rw"
LOAN_SPLIT_CARRIERS: tuple[str, str, str] = (
    LOAN_SPLIT_SHARE,
    LOAN_SPLIT_SECURED_RW,
    LOAN_SPLIT_RESIDUAL_RW,
)

#: The label each part carries (``"secured"`` / ``"residual"``; null on an unsplit row).
RW_PART_COL: str = "rw_part"

#: The weight a part bands on, and the Art. 123B snapshot that names the reported weight.
_RISK_WEIGHT: str = "risk_weight"
_PRE_MISMATCH_RW: str = "risk_weight_pre_currency_mismatch"
_MISMATCH_APPLIED: str = "currency_mismatch_multiplier_applied"

#: How far the reported weight may sit from the recorded blend and still be it. The
#: engine writes the carriers only where the two are bit-equal; this absorbs
#: nothing but a re-association of the same three floats.
_BLEND_TOLERANCE: float = 1e-12

#: The bindings a split leaves unchanged: sums add the parts back to the row, and
#: formulas / side inputs read no rows. A count or an average would not survive.
_ROW_SAFE_BINDINGS: tuple[type, ...] = (Sum, SafeSum, Formula, SideContext)

_ORDER: str = "__rw_part_order"
_PART_ORDER: str = "__rw_part_rank"


def split_risk_weight_parts(
    frame: pl.DataFrame,
    *,
    exposure_cols: Collection[str],
    rwea_cols: Collection[str],
) -> pl.DataFrame:
    """Split each loan-split row into its secured and residual parts.

    A row is split when the three carriers are non-null, its share lies strictly
    between 0 and 1, and its reported weight (the pre-multiplier one where Art.
    123B applied, else ``risk_weight``) equals the recorded blend. Each part takes
    its own weight in ``risk_weight`` (and in the Art. 123B snapshot, where the
    frame has one), its label in ``RW_PART_COL``, ``share`` / ``1 - share`` of every
    ``exposure_cols`` column and ``share x secured / blend`` / the rest of every
    ``rwea_cols`` column. The residual part is the row less the secured part, so
    the two add back to the row. Every other row is kept, in place and unchanged.

    Args:
        frame: A template's frame of ledger rows.
        exposure_cols: Amount columns to split by exposure share. Absent names are skipped.
        rwea_cols: Risk-weighted amount columns to split by RWEA share. Absent names are skipped.

    Returns:
        ``frame`` itself when it carries no loan-split row (no carriers, or none
        that still describe their row); otherwise the frame with each such row
        replaced by its two parts.

    Raises:
        ValueError: A column is named as both an exposure and an RWEA amount.
    """
    overlap = set(exposure_cols) & set(rwea_cols)
    if overlap:
        msg = f"columns cannot be split as both exposure and RWEA: {sorted(overlap)}"
        raise ValueError(msg)
    if not set(LOAN_SPLIT_CARRIERS) <= set(frame.columns):
        return frame
    indexed = frame.with_row_index(_ORDER)
    is_two_part = _is_two_part(set(frame.columns)).fill_null(value=False)
    two_part = indexed.filter(is_two_part)
    if two_part.is_empty():
        return frame

    share = pl.col(LOAN_SPLIT_SHARE)
    rwea_share = share * pl.col(LOAN_SPLIT_SECURED_RW) / _reported_weight(set(frame.columns))
    secured_amounts = {
        **{col: pl.col(col) * share for col in exposure_cols if col in frame.columns},
        **{col: pl.col(col) * rwea_share for col in rwea_cols if col in frame.columns},
    }
    residual_amounts = {col: pl.col(col) - amount for col, amount in secured_amounts.items()}
    whole = indexed.filter(~is_two_part).with_columns(
        pl.lit(None, dtype=pl.String).alias(RW_PART_COL), pl.lit(0).alias(_PART_ORDER)
    )
    return (
        pl.concat(
            [
                whole,
                _part(two_part, "secured", 0, LOAN_SPLIT_SECURED_RW, secured_amounts),
                _part(two_part, "residual", 1, LOAN_SPLIT_RESIDUAL_RW, residual_amounts),
            ],
            how="vertical_relaxed",
        )
        .sort(_ORDER, _PART_ORDER)
        .drop(_ORDER, _PART_ORDER)
    )


def summed_columns(spec: TemplateSpec) -> frozenset[str]:
    """Every column a ``spec``'s cells sum — what a split must scale to stay invisible.

    Raises:
        ValueError: A cell's binding is one a split would change (a count, a mean,
            a weighted average, a ratio, a prior-period read).
    """
    columns: set[str] = set()
    for key, cell in spec.cells.items():
        binding = cell.binding
        if not isinstance(binding, _ROW_SAFE_BINDINGS):
            msg = (
                f"{spec.name} cell {key}: a {type(binding).__name__} binding would change "
                "if its rows were split into parts"
            )
            raise ValueError(msg)
        if isinstance(binding, Sum):
            columns.add(binding.col)
        elif isinstance(binding, SafeSum):
            columns.update(binding.cols)
    return frozenset(columns)


def _reported_weight(cols: set[str]) -> pl.Expr:
    """The weight a row is reported against: pre-multiplier where Art. 123B applied."""
    applied = pl.col(_RISK_WEIGHT)
    if not {_PRE_MISMATCH_RW, _MISMATCH_APPLIED} <= cols:
        return applied
    return (
        pl.when(pl.col(_MISMATCH_APPLIED).fill_null(value=False))
        .then(pl.col(_PRE_MISMATCH_RW))
        .otherwise(applied)
    )


def _is_two_part(cols: set[str]) -> pl.Expr:
    """Carriers present, a genuine second part, and still the row's reported weight."""
    share = pl.col(LOAN_SPLIT_SHARE)
    blend = pl.col(LOAN_SPLIT_SECURED_RW) * share + pl.col(LOAN_SPLIT_RESIDUAL_RW) * (1.0 - share)
    weight = _reported_weight(cols)
    return (
        (share > 0.0)
        & (share < 1.0)
        & (weight > 0.0)
        & ((weight - blend).abs() <= _BLEND_TOLERANCE)
    )


def _part(
    rows: pl.DataFrame, label: str, rank: int, weight_col: str, amounts: dict[str, pl.Expr]
) -> pl.DataFrame:
    """One part of ``rows``: its amounts, and its own weight in place of the blend.

    Every expression reads ``rows`` as it was, so the RWEA share is taken off the
    reported weight the row came in with, not the part weight written beside it.
    """
    weights = [pl.col(weight_col).alias(_RISK_WEIGHT)]
    if _PRE_MISMATCH_RW in rows.columns:
        weights.append(pl.col(weight_col).alias(_PRE_MISMATCH_RW))
    return rows.with_columns(
        *(amount.alias(col) for col, amount in amounts.items()),
        *weights,
        pl.lit(label).alias(RW_PART_COL),
        pl.lit(rank).alias(_PART_ORDER),
    )
