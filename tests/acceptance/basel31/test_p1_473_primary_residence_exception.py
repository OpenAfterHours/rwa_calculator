# Art. 124F(1) on the first-charge legs: 0.55 x 500,000 at 20%, the rest at 75%.
_HOME_RWA = 275_000.0 * 0.20 + 25_000.0 * 0.75  # 73,750
_HOME_RW = _HOME_RWA / 300_000.0  # 0.245833...
# Art. 124G(1) Table 6B, 50% < LTV <= 60%.
_TABLE_6B_RWA = 300_000.0 * 0.35  # 105,000
# Art. 124G(2) junior charge: Table 6B x 1.25.
_JUNIOR_124G_RW = 0.35 * 1.25  # 0.4375
# Art. 124F(2)(a) junior charge under the rule: 25,000 at 20% + 25,000 at 75%.
_JUNIOR_124F_RULE_RW = (25_000.0 * 0.20 + 25_000.0 * 0.75) / 50_000.0  # 0.475
# Other residential RE: Art. 124J(1) 150% if materially dependent, else Art. 124J(2)
# the Art. 124L(1)(a) natural-person counterparty weight, 75%.
_OTHER_RRE_MD_RWA = 300_000.0 * 1.50  # 450,000
_OTHER_RRE_RW = 0.75
_OTHER_RRE_RWA = 300_000.0 * _OTHER_RRE_RW  # 225,000
# Commercial RE materially dependent (Art. 124E(6)): Art. 124I(1) 100% at LTV <= 80%.
_CRE_MD_RWA = 300_000.0 * 1.00  # 300,000
# Defaulted, no provisions: Art. 127(3) 100% when not materially dependent; the
# Art. 127(1)(a) 150% (specific credit risk adjustments < 20%) when it is.
_DEFAULTED_RWA = 300_000.0 * 1.00  # 300,000
_DEFAULTED_MD_RWA = 300_000.0 * 1.50  # 450,000
# Sole trader booked corporate: Art. 124F(1)(a) 275,000 x 20% on the _sec leg plus the
# engine's corporate 100% on the 25,000 _res leg (the rule's Art. 124L(1)(a) is 75%).
_SOLE_TRADER_RWA = 275_000.0 * 0.20 + 25_000.0 * 1.00  # 80,000


