class TestB31PrimaryResidenceException:
    """Art. 124E(1)(a) exempts a single primary-residence property from the (b) re-route."""

    def test_fixture_can_discriminate(self, b31: dict[str, LoanResult]) -> None:
        """Adequacy: every borrower but the control is over the limit, and the re-route fires."""
        # Arrange
        over_limit = {s.reference for s in LOANS if s.property_count == OVER_LIMIT_COUNT}

        # Assert
        assert over_limit == set(b31) - {LN_JUNIOR_CTRL}, "only the junior control is within"
        assert b31[LN_BTL].rwa == pytest.approx(_TABLE_6B_RWA, abs=0.01), (
            "the buy-to-let sibling is not on Art. 124G - the count re-route did not fire, "
            "so the home leg's move would prove nothing"
        )
        assert b31[LN_HOME].ead == pytest.approx(300_000.0, abs=0.01)

    def test_attested_home_takes_the_loan_split(self, b31: dict[str, LoanResult]) -> None:
        """A flagged single home over the limit is Art. 124F: 0.245833 / 73,750."""
        # Act
        home = b31[LN_HOME]

        # Assert
        assert home.has_income_cover is False
        assert home.risk_weight == pytest.approx(_HOME_RW, abs=1e-6)
        assert home.rwa == pytest.approx(_HOME_RWA, abs=0.01)

    @pytest.mark.parametrize(
        "loan",
        [LN_BTL, LN_UNKNOWN, LN_TWO_PROPS, LN_TWO_HOMES, LN_INCOME],
        ids=["buy_to_let", "not_attested", "home_plus_btl", "two_flagged", "explicit_income"],
    )
    def test_no_exception_without_a_single_attested_home(
        self, b31: dict[str, LoanResult], loan: str
    ) -> None:
        """No single attested primary residence, or an explicit income flag: Art. 124G 35%."""
        # Act
        result = b31[loan]

        # Assert
        assert result.has_income_cover is True
        assert result.risk_weight == pytest.approx(0.35, abs=1e-9)
        assert result.rwa == pytest.approx(_TABLE_6B_RWA, abs=0.01)

    def test_attested_home_other_rre_takes_the_counterparty_weight(
        self, b31: dict[str, LoanResult]
    ) -> None:
        """Non-qualifying RE on the flagged home: Art. 124J(2) 75% / 225,000, not 124J(1) 150%."""
        # Arrange
        assert b31[LN_OTHER_RRE_BTL].rwa == pytest.approx(_OTHER_RRE_MD_RWA, abs=0.01), (
            "the non-qualifying buy-to-let sibling is not on Art. 124J(1) 150% - the count "
            "re-route does not reach other RRE here, so the home leg's move would prove nothing"
        )

        # Act
        home = b31[LN_OTHER_RRE]

        # Assert
        assert home.has_income_cover is False
        assert home.risk_weight == pytest.approx(_OTHER_RRE_RW, abs=1e-9)
        assert home.rwa == pytest.approx(_OTHER_RRE_RWA, abs=0.01)

    def test_flagged_commercial_property_stays_materially_dependent(
        self, b31: dict[str, LoanResult]
    ) -> None:
        """A commercial property flagged as the home: Art. 124E(6) decides, 124I 100% / 300,000."""
        # Act
        commercial = b31[LN_COMMERCIAL]

        # Assert
        assert commercial.has_income_cover is True
        assert commercial.risk_weight == pytest.approx(1.00, abs=1e-9)
        assert commercial.rwa == pytest.approx(_CRE_MD_RWA, abs=0.01)

    def test_defaulted_attested_home_takes_art_127_3(self, b31: dict[str, LoanResult]) -> None:
        """A defaulted flagged home is not materially dependent: Art. 127(3) 100% / 300,000."""
        # Act
        defaulted = b31[LN_DEFAULTED]

        # Assert
        assert defaulted.has_income_cover is False
        assert defaulted.risk_weight == pytest.approx(1.00, abs=1e-9), (
            "1.50 is Art. 127(1)(a) - the re-route made the defaulted home materially dependent"
        )
        assert defaulted.rwa == pytest.approx(_DEFAULTED_RWA, abs=0.01)

    def test_sole_trader_attested_home_is_loan_split(self, b31: dict[str, LoanResult]) -> None:
        """A sole trader's flagged home becomes two split legs: 80,000, not one 300,000 row.

        The 80,000 weights the 25,000 ``_res`` leg at the corporate 100% where
        PS1/26 Art. 124L(1)(a) gives 75% (73,750): a known conservative overstatement
        pinned on purpose, OWNER: P1.483.
        """
        # Act
        sole_trader = b31[LN_SOLE_TRADER]

        # Assert
        assert sole_trader.legs == 2, "the row must reach the splitter as a candidate"
        assert sole_trader.has_income_cover is False
        assert sole_trader.ead == pytest.approx(300_000.0, abs=0.01)
        assert sole_trader.rwa == pytest.approx(_SOLE_TRADER_RWA, abs=0.01)

    def test_landlord_home_beside_own_buy_to_lets(self, b31: dict[str, LoanResult]) -> None:
        """One count-4 landlord: the home loan is Art. 124F, both buy-to-let loans 124G."""
        # Arrange
        group = {s.reference for s in LOANS if s.counterparty == LANDLORD_COUNTERPARTY}
        assert group == {LN_LL_HOME, LN_LL_BTL1, LN_LL_BTL2}, (
            "the landlord's loans must share ONE counterparty, or an obligor-scope "
            "single-property test would pass this leg"
        )

        # Act
        home, btl1, btl2 = b31[LN_LL_HOME], b31[LN_LL_BTL1], b31[LN_LL_BTL2]

        # Assert
        assert home.risk_weight == pytest.approx(_HOME_RW, abs=1e-6)
        assert home.rwa == pytest.approx(_HOME_RWA, abs=0.01)
        assert btl1.rwa == pytest.approx(_TABLE_6B_RWA, abs=0.01)
        assert btl2.rwa == pytest.approx(_TABLE_6B_RWA, abs=0.01)

    def test_junior_charge_on_home_moves_to_124f(self, b31: dict[str, LoanResult]) -> None:
        """The exception also applies to a junior charge, where Art. 124F is the HIGHER weight."""
        # Arrange
        control = b31[LN_JUNIOR_CTRL]
        assert control.has_income_cover is False, "the within-limit control must be Art. 124F"

        # Act
        junior = b31[LN_JUNIOR]

        # Assert
        assert junior.has_income_cover is False
        assert junior.risk_weight == pytest.approx(control.risk_weight, abs=1e-9)
        assert junior.risk_weight >= _JUNIOR_124F_RULE_RW - 1e-9
        assert junior.risk_weight > _JUNIOR_124G_RW, "a min(124F, 124G) would stay at 0.4375"


class TestB31OutputFloorBasis:
    """The exception reaches the output floor: an A-IRB mortgage's SA-equivalent moves too.

    PS1/26 Art. 92(2A) floors U-TREA at x * S-TREA, and S-TREA is each modelled
    exposure's SA-equivalent RWA (``sa_rwa``). The SA risk-weight pipeline runs on
    IRB rows as well, so the flagged home's SA-equivalent leaves Art. 124G for the
    Art. 124F split exactly as an SA row does (LESSONS D1).
    """

    @pytest.fixture(scope="class")
    def irb(self) -> tuple[dict[str, LoanResult], OutputFloorSummary]:
        """The P1.473 portfolio on A-IRB retail mortgages, and its floor summary."""
        return run_irb_portfolio()

    def test_floor_inputs_are_the_modelled_loans(
        self, irb: tuple[dict[str, LoanResult], OutputFloorSummary]
    ) -> None:
        """Adequacy: every loan is A-IRB and S-TREA is the sum of their SA-equivalents."""
        # Arrange
        loans, summary = irb

        # Assert
        assert {r.approach for r in loans.values()} == {"advanced_irb"}, (
            "a loan left A-IRB - its SA-equivalent would not be an output-floor input"
        )
        assert summary.s_trea == pytest.approx(
            sum(r.sa_rwa or 0.0 for r in loans.values()), abs=0.01
        )

    def test_attested_home_sa_equivalent_is_the_loan_split(
        self, irb: tuple[dict[str, LoanResult], OutputFloorSummary]
    ) -> None:
        """S-TREA carries the flagged home at Art. 124F 73,750, the buy-to-let at 124G 105,000."""
        # Arrange
        loans, _ = irb

        # Assert
        assert loans[LN_HOME].sa_rwa == pytest.approx(_HOME_RWA, abs=0.01)
        assert loans[LN_BTL].sa_rwa == pytest.approx(_TABLE_6B_RWA, abs=0.01)

    def test_other_rre_and_commercial_sa_equivalents(
        self, irb: tuple[dict[str, LoanResult], OutputFloorSummary]
    ) -> None:
        """S-TREA: the flagged other-RRE home at 124J(2) 225,000; the commercial at 124I 300,000."""
        # Arrange
        loans, _ = irb

        # Assert
        assert loans[LN_OTHER_RRE].sa_rwa == pytest.approx(_OTHER_RRE_RWA, abs=0.01)
        assert loans[LN_OTHER_RRE_BTL].sa_rwa == pytest.approx(_OTHER_RRE_MD_RWA, abs=0.01)
        assert loans[LN_COMMERCIAL].sa_rwa == pytest.approx(_CRE_MD_RWA, abs=0.01)

    def test_defaulted_and_landlord_sa_equivalents(
        self, irb: tuple[dict[str, LoanResult], OutputFloorSummary]
    ) -> None:
        """S-TREA: the defaulted home at Art. 127(3) 300,000; the landlord's home at 73,750."""
        # Arrange
        loans, _ = irb

        # Assert
        assert loans[LN_DEFAULTED].sa_rwa == pytest.approx(_DEFAULTED_RWA, abs=0.01), (
            f"{_DEFAULTED_MD_RWA:,.0f} is the Art. 127(1)(a) 150% of a materially dependent home"
        )
        assert loans[LN_LL_HOME].sa_rwa == pytest.approx(_HOME_RWA, abs=0.01)
        assert loans[LN_LL_BTL1].sa_rwa == pytest.approx(_TABLE_6B_RWA, abs=0.01)
        assert loans[LN_LL_BTL2].sa_rwa == pytest.approx(_TABLE_6B_RWA, abs=0.01)

    def test_junior_charge_sa_equivalent_rises(
        self, irb: tuple[dict[str, LoanResult], OutputFloorSummary]
    ) -> None:
        """The junior charge's SA-equivalent is the within-limit 124F value, above 124G(2)."""
        # Arrange
        loans, _ = irb
        junior, control = loans[LN_JUNIOR], loans[LN_JUNIOR_CTRL]
        assert junior.sa_rwa is not None and control.sa_rwa is not None

        # Assert
        assert junior.sa_rwa == pytest.approx(control.sa_rwa, abs=0.01)
        assert junior.sa_rwa > _JUNIOR_124G_RW * 50_000.0


