"""
P1.473 — PS1/26 Art. 124E(1)(a): a landlord's own home is not materially dependent.

Pipeline position:
    Loader -> HierarchyResolver -> Classifier -> CRMProcessor -> SACalculator -> Aggregator

Rule text (PS1/26 Art. 124E, ps126app1.pdf pp. 54-55, verbatim):
    "1. ... A residential real estate exposure is materially dependent on the
    cash-flows generated by the property unless it is: (a) to one or more natural
    persons and the exposure is secured by a single property that is the obligor's
    primary residence; (b) to one or more natural persons that individually meet
    the three property limit in accordance with paragraph 2; ..."
    "2. A natural person meets the three property limit ... if they have no more
    than three qualifying properties. A qualifying property is a property that is
    residential real estate, is not the primary residence of the natural person
    and that is either: (a) security for a residential real estate exposure to the
    natural person, regardless of which lender has the residential real estate
    exposure; or (b) ..."
    "4. For the purposes of paragraphs 1 to 3, each separate housing unit shall
    count as an individual property, including for real estate exposures secured
    by a single charge."

Limbs (a) and (b) are independent: a borrower over the three-property limit still
keeps Art. 124F on the loan secured by their primary residence alone. Before the
fix the engine had no primary-residence carrier, so the Art. 124E(2) count
re-route (P1.142) sent the landlord's own home to Art. 124G as well.

Scenario (natural-person borrowers, LTV 0.60, SA; every loan on its own
counterparty except the landlord group, which shares one):

- LN_HOME: 300,000 first charge on a 500,000 home flagged ``is_primary_residence``,
  borrower count 4. Art. 124F(1): 275,000 x 20% + 25,000 x 75% (Art. 124L(1)(a))
  = 73,750, RW 0.245833. Before the fix: Art. 124G Table 6B 35% = 105,000.
- LN_BTL (flag False), LN_UNKNOWN (flag null = not attested), LN_TWO_PROPS (home
  + buy-to-let pledged together: not "a single property"), LN_TWO_HOMES (two
  properties both flagged: still not a single property), LN_INCOME (flagged home
  but ``is_income_producing`` True: the institution's own dependence assessment
  stands) all stay Art. 124G: 35% = 105,000.
- LN_JUNIOR: 50,000 junior charge behind a 250,000 third-party prior charge on
  the flagged home, borrower count 4. Here the fix RAISES RWA. Art. 124G(2):
  Table 6B 35% x 1.25 = 0.4375 (21,875) before the fix. Art. 124F(2)(a) after it:
  the 20% band is 55% x 500,000 less the prior 250,000 = 25,000, so 25,000 x 20%
  + 25,000 x 75% = 23,750, RW 0.475 under the rule. The engine prices this leg at
  0.704167 (35,208.33) because of the separate stacked-LTV denominator defect
  (P1.449); the test pins it to the same engine weight as an otherwise identical
  borrower within the limit (LN_JUNIOR_CTRL) and to at least the rule's 0.475, so
  it holds whether or not P1.449 has landed, and it fails a benefit-only
  ``min(124F, 124G)`` implementation (which would give 0.4375).

- LN_OTHER_RRE: the same 300,000 first charge on the flagged home, but the property
  is not regulatory real estate (``is_qualifying_re`` False), so it is an "other"
  residential RE exposure under Art. 124J. Art. 124E(1) decides material dependence
  for it too, and limb (a) moves it from Art. 124J(1) ("150% to any other real
  estate exposure that is materially dependent") to Art. 124J(2) (the Art. 124L
  counterparty weight, 75% for a natural person under Art. 124L(1)(a)): 1.50 /
  450,000 before the fix, 0.75 / 225,000 after — the largest per-exposure cut this
  change makes. LN_OTHER_RRE_BTL (same, flagged False) stays Art. 124J(1) 150%.
- LN_COMMERCIAL: a commercial-typed property flagged ``is_primary_residence``. Limb
  (a) is a limb of the RESIDENTIAL test; a commercial exposure is decided by
  Art. 124E(6) — materially dependent "except where each property ... is
  predominantly used by the borrower for its own business purpose", which a home is
  not. So the flag grants nothing: Art. 124I(1) 100% (LTV <= 80%) = 300,000, before
  and after the fix.
- LN_DEFAULTED: the LN_HOME loan with the borrower in default and no provisions.
  PS1/26 Art. 127(3): "A residential real estate exposure which is a defaulted
  exposure and is not materially dependent on the cash-flows of the property shall
  be assigned a risk weight of 100%". Before the fix the count re-route made it
  materially dependent, so Art. 127(1)(a) 150% applied (specific credit risk
  adjustments below 20%): 450,000. After it: 100% = 300,000.
- LN_SOLE_TRADER: the LN_HOME loan to a natural person booked ``entity_type``
  corporate (the sole trader ``docs/data-model/input-schemas.md`` documents),
  product term_loan. Before the fix the re-route set ``has_income_cover``, so the
  splitter left it as ONE corporate row at 100% = 300,000 (that 100% is the
  separate P1.262 routing gap). After it the row is a loan-split candidate and
  comes back as TWO legs: ``_sec`` 275,000 x 20% (Art. 124F(1)(a)) on the
  real-estate class plus ``_res`` 25,000 at the corporate 100% = 80,000. The rule's
  residual is Art. 124L(1)(a) 75% for a natural person (73,750 in all); the 100% is
  a separate defect, pinned here so a fix to it shows.
- The landlord group (LN_LL_HOME, LN_LL_BTL1, LN_LL_BTL2): ONE count-4
  counterparty with a home loan and two buy-to-let loans, each on its own
  property — the landlord's usual book. The home loan takes Art. 124F 0.245833 /
  73,750 and each buy-to-let stays Art. 124G 35% = 105,000. Limb (a) is a test of
  the EXPOSURE's security, so the obligor's other pledged properties do not deny it.

Output floor: run on A-IRB retail mortgages, the same loans' SA-equivalent RWA (the
S-TREA input of PS1/26 Art. 92(2A)) moves the same way — LN_HOME and LN_LL_HOME
105,000 -> 73,750, LN_OTHER_RRE 450,000 -> 225,000, LN_DEFAULTED 450,000 ->
300,000, LN_JUNIOR up to its within-limit 124F value — so the exception lowers or
raises the floor threshold as well as SA RWA. (The sole trader is booked corporate,
outside the run's retail-mortgage model permission, so it is measured on SA only.)

CRR has no primary-residence or three-property test (CRR Art. 125(1)(a): residential
property "occupied or let by the owner" at 35%); the re-route sits behind the
Basel 3.1 Feature ``b31_art_124e_three_property_limit_applies``, so CRR stays
0.35 / 105,000 on every first-charge leg, and the defaulted home takes CRR
Art. 127(3) 100% (exposures "fully and completely secured by mortgages on
residential property") = 300,000.

References:
    - PS1/26 Art. 124E(1)(a)/(b), (2), (4), (6); Art. 124F(1)-(2); Art. 124G(1)-(2);
      Art. 124I(1); Art. 124J(1)-(2); Art. 124L(1)(a); Art. 127(1), (3);
      Art. 92(2A) (output floor)
    - CRR Art. 125(1)(a); Art. 127(3)
    - IMPLEMENTATION_PLAN.md: P1.473 (review RE-18)
"""

