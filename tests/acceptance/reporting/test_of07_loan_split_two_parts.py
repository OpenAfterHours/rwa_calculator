@pytest.mark.parametrize(
    ("rule_id", "z_code"),
    [("boe_b0445", None), ("boe_b0445_1", None), ("boe_b1009", "0010"), ("boe_b1013", "0010")],
)
def test_the_gateway_rules_on_real_estate_risk_weight_rows_hold(
    rich: tuple[pl.DataFrame, COREPTemplateBundle], rule_id: str, z_code: str | None
) -> None:
    """``boe_b0445``: row 0280 empty on sheet 0010. ``boe_b1009`` / ``boe_b1013``: the
    20% / 75% rows' RWEA at least their weight, now evaluated on sheet 0010 as well."""
    header = ReturnHeader(_ENTITY_IDENTIFIER, date(2027, 3, 31), FILING_MODULE)
    pack = resolve_release(FILING_MODULE, FILING_TAXONOMY).pack
    mapping = build_canonical_return(rich[1], header, pack=pack)
    validation, trace = trace_return(mapping.canonical, pack)
    assert trace is not None

    verdicts = [result for result in validation.report.results if result.rule_id == rule_id]
    assert len(verdicts) == 1, f"expected one {rule_id} verdict, got {len(verdicts)}"
    assert verdicts[0].status == STATUS_PASS, f"{rule_id}: {verdicts[0]}"
    if z_code is not None:
        on_sheet = [
            evaluation.holds
            for evaluation in trace.evaluations
            if evaluation.rule_id == rule_id and ("z", z_code) in evaluation.place
        ]
        assert on_sheet == [True], f"{rule_id} on z{z_code}: {on_sheet}"


def test_a_loan_short_of_the_55_percent_cap_stays_whole() -> None:
    """The survivor leg (LESSONS B5): a 50% LTV loan is all 20%, so there is no second part.

    CONTROL, not a detector: green before and after. Its mutation is dropping the
    ``0 < share < 1`` gate in BOTH the engine and the kernel (each alone is pinned by
    its own unit test): the loan then splits into itself and an empty residual part,
    so the sheet's plan holds it twice. The empty part's weight is the counterparty's
    (this borrower is not flagged a natural person), so it would land on whatever row
    that weight bands to; the plan, not one row, is what can see it.
    """
    results, corep = _run("row-scope")
    loan = _leg(results, ROW_SCOPE_LN_RRE)
    assert float(loan["ltv"]) <= _CAP
    assert float(loan["risk_weight"]) == pytest.approx(_SECURED_RW)
    sheet = _sheet_key("0010")
    plan = c07_plans(results.lazy(), set(results.columns), _FRAMEWORK, [])[sheet]

    assert plan.frame.filter(pl.col("exposure_reference") == ROW_SCOPE_LN_RRE).height == 1
    assert _cell(corep, sheet, _ROW_SECURED, "0200") == pytest.approx(ROW_SCOPE_DRAWN_RRE)
    assert _cell(corep, sheet, _ROW_SECURED, "0220") == pytest.approx(
        ROW_SCOPE_DRAWN_RRE * _SECURED_RW
    )


def test_splitting_moves_nothing_but_the_risk_weight_rows(
    rich: tuple[pl.DataFrame, COREPTemplateBundle],
) -> None:
    """CONTROL for double counting: every cell outside rows 0140-0280 is the unsplit figure.

    Its mutation: leave one summed column (e.g. ``reporting_gross_on_bs``) out of the
    scaled set, and row 0010 col 0010 rises by the loan's 400,000.
    """
    split = rich[1].c07_00
    unsplit = _run("rich", carriers=False)[1].c07_00
    assert set(split) == set(unsplit)
    outside = pl.col("row_ref").is_between(pl.lit(_FIRST_RW_ROW), pl.lit(_LAST_RW_ROW)).not_()

    for sheet, frame in split.items():
        assert frame.filter(outside).equals(unsplit[sheet].filter(outside)), sheet


@pytest.mark.parametrize("column", _FOOTING_COLUMNS)
def test_the_risk_weight_rows_foot_to_row_0010(
    rich: tuple[pl.DataFrame, COREPTemplateBundle],
    real_estate_sheet: str,
    total_sheet: str,
    column: str,
) -> None:
    corep = rich[1]
    for sheet in (real_estate_sheet, total_sheet):
        frame = corep.c07_00[sheet]
        banded = frame.filter(
            pl.col("row_ref").is_between(pl.lit(_FIRST_RW_ROW), pl.lit(_LAST_RW_ROW))
        )[column].sum()

        assert banded == pytest.approx(_cell(corep, sheet, "0010", column)), sheet
