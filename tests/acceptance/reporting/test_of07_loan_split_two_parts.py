"""
OF 07.00: a loan-split real-estate exposure is reported in its two risk-weight parts.

Pipeline position:
    build_reporting_bundle() -> PipelineOrchestrator (Basel 3.1, rich, as the golden
        gate runs it) -> COREPGenerator -> OF 07.00 sheet 0010 (Art. 112(1)(i) real
        estate) and the Total sheet -> filing.build_canonical_return -> rwa_filer.boe

What is asserted, and the text it is asserted from:

- PS1/26 Annex II (ps1-26-annex-ii-reporting-instructions.pdf) p.94, OF 07.00 rows
  0140-0280: "Real estate exposures classified as regulatory real estate
  (residential or commercial) which are not materially dependent on the cash flows
  generated by the property (Articles 124F and 124H ...) shall be reported in two
  parts, against the risk weight applied to the portion up to 55% of the value of
  the property, and against the portion above 55% of the value of the property (if
  applicable)."
- PS1/26 Art. 124F(1) (ps126app1.pdf p.55): "(a) the part of the exposure up to 55%
  of the value of the property shall be assigned a risk weight of 20%; and (b) the
  risk weight of the counterparty shall be applied to the residual part of the
  exposure, if any, in accordance with Article 124L". Art. 124L(1)(a) (p.58): "for
  an exposure to a natural person or persons that is not an exposure to an SME,
  75%".
- Both parts stay on the real-estate sheet: Art. 112(2) Table A2 ranks real estate
  (row 7) above retail and corporates, and Art. 123(2) "Retail exposures shall
  exclude real estate exposures".

``RP-LN-RRE`` (400,000 at 60% LTV to a natural person) is the row past the 55% cap;
``RSC-LN-RRE`` of the row-scope book (400,000 at 50% LTV) is the row short of it
(LESSONS B5, fourth form). Weighted at its one blended weight (24.58%), the rich
loan matched no published row and fell to row 0280 "Other risk weights", which the
Bank's ``boe_b0445`` requires empty on sheet 0010.

References:
- PS1/26 Art. 112(2), 123(2), 124F, 124L; Annex II OF 07.00 rows 0140-0280 (p.94)
- src/rwa_calc/reporting/kernel/rw_parts.py; src/rwa_calc/reporting/corep/c07.py
"""

