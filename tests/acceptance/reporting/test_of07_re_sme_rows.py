class TestUnsplitSmeCommercialLegFootsRow0340:
    """P1.378: an SME leg on the real-estate sheet is inside row 0341, not beside it."""

    def test_the_probe_carries_an_unsplit_sme_leg_on_the_real_estate_sheet(self) -> None:
        """Adequacy (LESSONS C11): the defect fires only where the SME flag is True
        on a commercial non-materially-dependent leg of the sheet. Unless the SME
        leg kept the corporate_sme class and reports in class (i), this file
        proves nothing about row 0341."""
        leg = _leg("cre", "b31", LN_SME_CRE)
        twin = _leg("cre", "b31", LN_LARGE_CRE)

        assert leg["exposure_class"] == "corporate_sme"
        assert leg["reporting_class_origin"] == "commercial_mortgage"
        assert leg["is_sme"] is True
        assert leg["property_type"] == "commercial"
        assert leg["has_income_cover"] is not True
        assert leg["risk_weight"] == pytest.approx(0.60), (
            "not weighted under Art. 124H(1) - the leg is not in the regulatory limb "
            "and rows 0340-0344 cannot see it"
        )
        assert twin["reporting_class_origin"] == "commercial_mortgage"
        assert twin["is_sme"] is False

    @pytest.mark.parametrize("col", _MONEY_COLS)
    def test_row_0340_is_the_sum_of_rows_0341_and_0342(self, col: str) -> None:
        """boe_b0732 (ERROR): r0340 = r0341 + r0342. Before the fix r0341 left the
        SME leg out: 3,000,000 against 2,000,000 + nothing."""
        sheet = _corep("cre", "b31").c07_00["real_estate"]

        expected = _cell(sheet, "0340", col)
        actual = _cell(sheet, "0341", col) + _cell(sheet, "0342", col)

        assert expected > 0.0, "row 0340 is empty - the identity would hold at 0 = 0"
        assert actual == pytest.approx(expected)

    def test_row_0341_reports_every_non_dependent_commercial_leg(self) -> None:
        """Row 0341 is all Art. 124H regulatory CRE: the large corporate's
        2,000,000 and the SME's 1,000,000 (2,000,000 before the fix)."""
        sheet = _corep("cre", "b31").c07_00["real_estate"]

        assert _cell(sheet, "0341", "0200") == pytest.approx(DRAWN_LARGE_CRE + DRAWN_SME_CRE)

    def test_row_0343_keeps_the_sme_leg(self) -> None:
        """Row 0343 carries the SME leg alone. Green before the fix too (the class
        name says SME): the guard that the sealed-flag change keeps it."""
        sheet = _corep("cre", "b31").c07_00["real_estate"]

        assert _cell(sheet, "0343", "0200") == pytest.approx(DRAWN_SME_CRE)

    @pytest.mark.parametrize("col", _MONEY_COLS)
    def test_row_0343_is_an_of_which_of_row_0341_when_the_sme_leg_is_alone(self, col: str) -> None:
        """boe_b0960 (ERROR): r0343 <= r0341. With the SME leg the only
        commercial leg, row 0341 was empty before the fix: 1,000,000 <= 0."""
        sheet = _corep("cre_alone", "b31").c07_00["real_estate"]

        assert _cell(sheet, "0343", col) > 0.0, "row 0343 is empty - 0 <= 0 proves nothing"
        assert _cell(sheet, "0343", col) <= _cell(sheet, "0341", col)

    def test_crr_declares_no_commercial_real_estate_detail_rows(self) -> None:
        """CRR C 07.00 has no rows 0340-0344 (CRR Annex II); the 0341 change is
        Basel 3.1 only."""
        sheet = _corep("cre", "crr").c07_00["real_estate"]

        refs = set(sheet["row_ref"].to_list())

        assert refs.isdisjoint({"0340", "0341", "0342", "0343", "0344"})


class TestSmeObligorRealEstateLegsReachRow0020:
    """P1.339: an SME obligor's split real-estate leg is an exposure to an SME."""

    @pytest.mark.parametrize("regime_key", list(_REGIMES))
    def test_the_split_secured_leg_is_sme_under_another_class_name(self, regime_key: str) -> None:
        """Adequacy: the secured leg is renamed residential_mortgage by the split
        and still sealed is_sme True. If the class still said SME the old flag
        would have found it and this class would test nothing."""
        leg = _leg("rre", regime_key, LN_SME_RRE + SECURED_SUFFIX)

        assert leg["exposure_class"] == "residential_mortgage"
        assert leg["is_sme"] is True
        assert leg["ead_final"] == pytest.approx(SME_RRE_SECURED[regime_key])

    @pytest.mark.parametrize("regime_key", list(_REGIMES))
    def test_real_estate_sheet_row_0020_counts_the_split_secured_leg(self, regime_key: str) -> None:
        """Row 0020 on the real-estate sheet = the SME's split secured RRE leg,
        the only leg on that sheet. Empty before the fix in both regimes."""
        sheet = _corep("rre", regime_key).c07_00["real_estate"]

        expected = SME_RRE_SECURED[regime_key]

        assert _cell(sheet, "0020", "0200") == pytest.approx(expected)
        assert _cell(sheet, "0020", "0010") == pytest.approx(expected)

    @pytest.mark.parametrize("regime_key", list(_REGIMES))
    def test_total_sheet_row_0020_is_every_exposure_to_the_sme(self, regime_key: str) -> None:
        """ "All exposures to SMEs": on the Total sheet, everything lent to the SME
        obligor, whichever class each leg landed in. Before the fix only the
        residual leg (CRR 200,000, Basel 3.1 450,000)."""
        sheet = _corep("rre", regime_key).c07_00["total"]

        assert _cell(sheet, "0020", "0200") == pytest.approx(DRAWN_SME_RRE)

    @pytest.mark.parametrize("regime_key", list(_REGIMES))
    def test_c09_01_real_estate_sme_row_ties_to_c07_row_0020(self, regime_key: str) -> None:
        """C 09.01 row 0095 ("secured by mortgages ... of which: SME") is defined
        as C 07.00 row 0020 of the real-estate class (boe_b0990-b0992 under
        Basel 3.1). Both must count the split secured leg: before the fix CRR
        tied at nothing = nothing, Basel 3.1 at 550,000 against nothing."""
        corep = _corep("rre", regime_key)
        c07 = corep.c07_00["real_estate"]
        c09 = corep.c09_01["GB"]

        assert _cell(c07, "0020", "0200") == pytest.approx(SME_RRE_SECURED[regime_key])
        for c09_col, c07_col in (("0010", "0010"), ("0075", "0200"), ("0090", "0220")):
            assert _cell(c09, "0095", c09_col) == pytest.approx(_cell(c07, "0020", c07_col))


class TestReSplitSmeSecuredLeg:
    """The registered b31/re-split portfolio: the SME secured leg reaches 0343 and stays in 0341."""

    def test_the_portfolio_carries_sme_and_non_sme_non_dependent_cre_legs(self) -> None:
        """Adequacy: one SME leg that must reach row 0343 and stay in 0341, and
        non-SME legs that must stay in 0341 only. A flag-only fix moves the
        first out of 0341; a 0341-only fix leaves 0343 empty."""
        results = _re_split_results()
        sme = results.filter(pl.col("exposure_reference") == LN_CRE_SME + SECURED_SUFFIX)
        non_sme = results.filter(
            pl.col("exposure_reference").is_in([LN_CRE_CORP, LN_MIXED + MIXED_CRE_SUFFIX])
        )

        assert sme.height == 1
        assert sme["exposure_class"][0] == "commercial_mortgage"
        assert sme["is_sme"][0] is True
        assert sme["has_income_cover"][0] is not True
        assert non_sme.height == 2
        assert not any(non_sme["is_sme"].to_list())

    def test_row_0343_carries_the_sme_secured_leg(self) -> None:
        """0.55 x 1,500,000 = 825,000 at the Art. 124H(1)(a) 60%: RWEA 495,000.
        Null before the fix."""
        sheet = _re_split_corep().c07_00["real_estate"]

        assert _cell(sheet, "0343", "0010") == pytest.approx(825_000.0)
        assert _cell(sheet, "0343", "0200") == pytest.approx(825_000.0)
        assert _cell(sheet, "0343", "0220") == pytest.approx(495_000.0)

    def test_row_0341_keeps_the_sme_secured_leg(self) -> None:
        """825,000 SME + 1,000,000 LN_CRE_CORP whole + 550,000 LN_MIXED CRE. A fix
        that corrected the SME flag and kept 0341 non-SME would drop this to
        1,550,000."""
        sheet = _re_split_corep().c07_00["real_estate"]

        assert _cell(sheet, "0341", "0200") == pytest.approx(2_375_000.0)

    @pytest.mark.parametrize("col", _MONEY_COLS)
    def test_the_commercial_rows_foot(self, col: str) -> None:
        """boe_b0732 and boe_b0960 on the registered portfolio."""
        sheet = _re_split_corep().c07_00["real_estate"]

        assert _cell(sheet, "0340", col) == pytest.approx(
            _cell(sheet, "0341", col) + _cell(sheet, "0342", col)
        )
        assert _cell(sheet, "0343", col) <= _cell(sheet, "0341", col)

    def test_real_estate_sheet_row_0020_reports_the_sme_secured_leg(self) -> None:
        """boe_b0990-b0992: OF 07.00 real-estate r0020 against OF 09.01 r0095."""
        corep = _re_split_corep()
        c07 = corep.c07_00["real_estate"]
        c09 = corep.c09_01["GB"]

        assert _cell(c07, "0020", "0200") == pytest.approx(825_000.0)
        for c09_col, c07_col in (("0010", "0010"), ("0075", "0200"), ("0090", "0220")):
            assert _cell(c09, "0095", c09_col) == pytest.approx(_cell(c07, "0020", c07_col))

    def test_total_sheet_reports_the_sme_obligor_in_full(self) -> None:
        """Total r0343 = the secured leg; r0020 = secured 825,000 + residual
        175,000 (175,000 alone before the fix)."""
        sheet = _re_split_corep().c07_00["total"]

        assert _cell(sheet, "0343", "0200") == pytest.approx(825_000.0)
        assert _cell(sheet, "0020", "0200") == pytest.approx(1_000_000.0)


