def _cre_bundle() -> RawDataBundle:
    """The SME and the large corporate, one loan-level CRE loan each, no collateral file."""
    return _bundle(
        [(CP_SME, 10_000_000.0), (CP_LARGE, 250_000_000.0)],
        [
            _loan(LN_SME_CRE, CP_SME, DRAWN_SME_CRE, property_type="commercial", ltv=CRE_LTV),
            _loan(LN_LARGE_CRE, CP_LARGE, DRAWN_LARGE_CRE, property_type="commercial", ltv=CRE_LTV),
        ],
    )


def _cre_alone_bundle() -> RawDataBundle:
    """The SME's loan-level CRE loan alone, no collateral file."""
    return _bundle(
        [(CP_SME, 10_000_000.0)],
        [_loan(LN_SME_CRE, CP_SME, DRAWN_SME_CRE, property_type="commercial", ltv=CRE_LTV)],
    )


def _rre_bundle() -> RawDataBundle:
    """The SME's loan secured on a qualifying residential property."""
    collateral = pl.DataFrame(
        [_residential_pledge(LN_SME_RRE, VALUE_SME_RRE, DRAWN_SME_RRE)],
        schema_overrides=dtypes_of(COLLATERAL_SCHEMA),
    )
    return _bundle(
        [(CP_SME, 10_000_000.0)],
        [_loan(LN_SME_RRE, CP_SME, DRAWN_SME_RRE, property_type=None, ltv=None)],
        collateral=collateral,
    )


_PROBE_BOOKS: dict[str, Callable[[], RawDataBundle]] = {
    "cre": _cre_bundle,
    "cre_alone": _cre_alone_bundle,
    "rre": _rre_bundle,
}


def _bundle(
    obligors: list[tuple[str, float]],
    loans: list[dict[str, object]],
    *,
    collateral: pl.DataFrame | None = None,
) -> RawDataBundle:
    counterparties = pl.DataFrame(
        [_counterparty(ref, annual_revenue=revenue) for ref, revenue in obligors],
        schema_overrides=dtypes_of(COUNTERPARTY_SCHEMA),
    )
    loan_frame = pl.DataFrame(loans, schema_overrides=dtypes_of(LOAN_SCHEMA))
    if collateral is None:
        return make_raw_bundle(counterparties=counterparties, loans=loan_frame)
    return make_raw_bundle(counterparties=counterparties, loans=loan_frame, collateral=collateral)


def _counterparty(reference: str, *, annual_revenue: float) -> dict[str, object]:
    """An unrated GB corporate; revenue alone decides SME (Glossary / Art. 4(1)(128D))."""
    return {
        "counterparty_reference": reference,
        "counterparty_name": reference,
        "entity_type": "corporate",
        "country_code": "GB",
        "annual_revenue": annual_revenue,
        "default_status": False,
    }


def _loan(
    reference: str, cp_ref: str, drawn: float, *, property_type: str | None, ltv: float | None
) -> dict[str, object]:
    """A drawn senior term loan; ``property_type`` and ``ltv`` on the loan, in a book
    with no collateral file, put it in class (i) as regulatory real estate without
    making it a split candidate."""
    return {
        "loan_reference": reference,
        "counterparty_reference": cp_ref,
        "product_type": "term_loan",
        "drawn_amount": drawn,
        "currency": "GBP",
        "value_date": date(2015, 1, 1),
        "maturity_date": date(2035, 12, 31),
        "seniority": "senior",
        "is_defaulted": False,
        "property_type": property_type,
        "ltv": ltv,
    }


def _residential_pledge(loan_ref: str, market_value: float, exposure: float) -> dict[str, object]:
    """A qualifying residential pledge, attested the way the splitter's candidate
    gate reads it (``reporting_re_split_portfolio._property`` explains each field)."""
    return {
        "collateral_reference": f"{loan_ref}-COL",
        "collateral_type": "real_estate",
        "currency": "GBP",
        "market_value": market_value,
        "nominal_value": market_value,
        "beneficiary_type": "loan",
        "beneficiary_reference": loan_ref,
        "residual_maturity_years": 10.0,
        "original_maturity_years": 20.0,
        "is_eligible_financial_collateral": False,
        "is_eligible_irb_collateral": True,
        "valuation_date": date(2015, 1, 1),
        "valuation_type": "market",
        "property_type": "residential",
        "property_ltv": exposure / market_value,
        "is_income_producing": False,
        "is_adc": False,
        "is_presold": False,
        "is_qualifying_re": True,
        "prior_charge_ltv": 0.0,
    }
