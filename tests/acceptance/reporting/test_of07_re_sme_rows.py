def _config(regime_key: str) -> CalculationConfig:
    """The registered SA configs (``_sa_config`` in ``test_supervisory_validations.py``)."""
    if regime_key == "crr":
        return CalculationConfig.crr(
            reporting_date=date(2025, 12, 31), permission_mode=PermissionMode.STANDARDISED
        )
    return CalculationConfig.basel_3_1(
        reporting_date=date(2027, 6, 1), permission_mode=PermissionMode.STANDARDISED
    )


@cache
def _probe_run(book: str, regime_key: str) -> tuple[pl.DataFrame, COREPTemplateBundle]:
    result = PipelineOrchestrator().run_with_data(_PROBE_BOOKS[book](), _config(regime_key))
    corep = COREPGenerator().generate_from_lazyframe(result.results, framework=_REGIMES[regime_key])
    return result.results.collect(), corep


@cache
def _re_split_run() -> tuple[pl.DataFrame, COREPTemplateBundle]:
    result = PipelineOrchestrator().run_with_data(build_reporting_re_split_bundle(), _config("b31"))
    corep = COREPGenerator().generate_from_lazyframe(result.results, framework="BASEL_3_1")
    return result.results.collect(), corep


def _corep(book: str, regime_key: str) -> COREPTemplateBundle:
    return _probe_run(book, regime_key)[1]


def _re_split_results() -> pl.DataFrame:
    return _re_split_run()[0]


def _re_split_corep() -> COREPTemplateBundle:
    return _re_split_run()[1]


def _leg(book: str, regime_key: str, reference: str) -> dict[str, object]:
    legs = _probe_run(book, regime_key)[0].filter(pl.col("exposure_reference") == reference)
    assert legs.height == 1, f"{regime_key}: expected one {reference!r} leg, got {legs.height}"
    return legs.row(0, named=True)


def _cell(frame: pl.DataFrame, row_ref: str, col: str) -> float:
    """A cell's value; an unreported cell reads 0.0 here, as the Bank's rules read it."""
    rows = frame.filter(pl.col("row_ref") == row_ref)
    assert rows.height == 1, f"expected one row {row_ref!r}, got {rows.height}"
    value = rows[col][0]
    return 0.0 if value is None else float(value)


