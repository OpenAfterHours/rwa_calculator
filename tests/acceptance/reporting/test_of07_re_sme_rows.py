"""
C 07.00 / OF 07.00 "of which: SME" on the real-estate sheet — rows 0020, 0341 and 0343.

Pipeline position:
    probe bundle / build_reporting_re_split_bundle() -> PipelineOrchestrator
        -> AggregatedResultBundle -> COREPGenerator

Why this exists (plan items P1.378 and P1.339, one change). Two defects on the
same rows, which have to be fixed together because each one on its own breaks
the identity the other one protects:

1. **Row 0341 left the SME legs out (P1.378, Basel 3.1).** PS1/26 Annex II
   (p.91): row 0340 is "Sum of rows 0341 and 0342"; row 0341 is the
   Art. 124H regulatory commercial real estate "not materially dependent on the
   cash flows generated by the property", with no SME qualifier; row 0343 is
   "Exposures to SMEs ... within Article 124H" — an of-which INSIDE 0341. The
   PRA001 v4.1.1 taxonomy nests it the same way (0343 carries 0341's dimensions
   plus the SME counterparty dimension), and the Bank's ERROR rules
   ``boe_b0732`` (0340 = 0341 + 0342) and ``boe_b0960`` (0343 <= 0341) check
   it. The row filter scoped 0341 to non-SME legs, so an SME leg on the sheet
   sat in 0343 and in NEITHER summand of 0340.
2. **The SME flag never reached the real-estate rows (P1.339, both regimes).**
   Row 0020 is "All exposures to SMEs" (PS1/26 Annex II p.88; CRR Annex II
   C 07.00). The flag read the exposure-class NAME, and the loan-splitter
   renames an SME obligor's secured leg ``commercial_mortgage`` /
   ``residential_mortgage``, so the leg left every SME row of the sheet while
   the sealed ``is_sme`` still said SME.

Fixing (2) alone moves the SME leg OUT of 0341 and breaks ``boe_b0732`` on the
registered ``b31/re-split``; fixing (1) alone leaves 0343 / 0020 empty. The
re-split class below therefore asserts both the row that must move (0343) and
the row that must not (0341).

Three probe books are built here (none registered in ``RUNS`` — every cell they
reach is live on the registered ``b31/re-split`` once the fix lands):

    book      | ref           | obligor | property            | legs
    ----------|---------------|---------|---------------------|-------------------------
    CRE       | LN_SME_CRE    | SME     | loan-level CRE, LTV | 1 corporate_sme, RE sheet
    CRE       | LN_LARGE_CRE  | large   | loan-level CRE, LTV | 1 corporate, RE sheet
    CRE_ALONE | LN_SME_CRE    | SME     | loan-level CRE, LTV | 1 corporate_sme, RE sheet
    RRE       | LN_SME_RRE    | SME     | RRE collateral      | sec 800,000 + res 200,000 (CRR)
              |               |         |                     | sec 550,000 + res 450,000 (B3.1)

``LN_SME_CRE`` is the only shape that reaches defect (1) on a production frame:
the classifier keeps it ``corporate_sme`` (no collateral row, so no split) and
the aggregator puts it on the real-estate sheet through ``property_type``, so the
class name still says SME. Its loan-level LTV is what makes it REGULATORY real estate
(Art. 124A(1)(d): a property with no value is other real estate, rows 0350-0354,
``corep/re_limbs.py``), so Basel 3.1 weights it under Art. 124H(1) at 60%.
``LN_LARGE_CRE`` keeps row 0341 live in the pre-fix
state (LESSONS B5's two-leg pattern); ``CRE_ALONE`` drops it, so row 0341 is
empty before the fix and ``boe_b0960`` (0343 <= 0341) is red as well. The CRE
books carry NO collateral file: any collateral file at all replaces a loan's own
``property_type`` with the (null) collateral one
(``engine/hierarchy/enrich.py::add_collateral_ltv``), which would take the leg off
the real-estate sheet and make this half of the file vacuous. ``LN_SME_RRE`` is
the shape that reaches defect (2) in BOTH regimes, so each regime is shown to
fail on its own (LESSONS C7): its secured leg is ``residential_mortgage`` with
``is_sme`` True.

References:
- PRA PS1/26 Annex II, OF 07.00 row 0020 (p.88) and rows 0340-0344 (p.91)
- CRR Annex II (COREP), C 07.00 row 0020
- PRA PS1/26 Art. 124F, 124H(1)-(3); CRR Art. 124 / 125 (the split legs)
- Bank of England v4.1.1 rules boe_b0732, boe_b0960 (ERROR) and
  boe_b0990 / boe_b0991 / boe_b0992 (WARNING, OF 09.01 r0095 vs OF 07.00 r0020)
"""

