"""
Integration tests: the property kind routes a real-estate row whatever its case (P1.362).

Pipeline position:
    Loader -> HierarchyResolver -> Classifier -> CRMProcessor
        -> RealEstateSplitter -> SA / IRB calculators -> Aggregator

Key responsibilities (each pinned in BOTH regimes, hand-calculated):
- The input contract accepts ``property_type`` case-insensitively
  (``contracts/validation.py``, pinned by ``test_validation.py::test_case_insensitive``),
  so ``"Commercial"`` raises no DQ006. Before P1.362 the SA real-estate routing
  matched it case-sensitively (``re_class.is_commercial_re_class``, the Basel 3.1
  ``b31_real_estate_route``): a retail-mortgage row secured on commercial
  property spelt ``"Commercial"`` missed the commercial limb and was priced on
  the residential ladder through its class string, with no error raised. The
  hierarchy now lowercases ``property_type`` once — the same normalisation the
  input contract's DQ006 check applies — so every exact-match reader sees
  ``"commercial"`` / ``"residential"``.
- The same routing feeds the Basel 3.1 output floor's SA-equivalent for an IRB
  row (``sa/calculator.py`` runs the SA ladder unconditionally, LESSONS D1) and
  the CRR Art. 164(4) commercial LGD-floor bucket (IRB007).
- The fix moves capital in BOTH directions, and every moved figure lands on the
  value the lowercase spelling already produced. It raises RWA where the
  property-kind miss fell through to the residential ladder (a retail-mortgage
  row) and lowers it where the miss fell through to the obligor's unsecured
  weight (a retail-other, SME or corporate row secured on commercial property
  that is not income-producing and, under CRR, is attested qualifying). The
  reducing limbs are pinned here with absolute figures, including one that
  reaches ``rwa_final`` through a binding output floor.

Rule text relied on (verbatim):
- CRR Art. 126(1)(a): "exposures or any part of an exposure fully and completely
  secured by mortgages on offices or other commercial premises may be assigned a
  risk weight of 50 %".
- CRR Art. 126(2)(d): "the 50 % risk weight ... shall be assigned to the part of
  the loan that does not exceed 50 % of the market value of the property".
- CRR Art. 124(1): "An exposure or any part of an exposure fully secured by
  mortgage on immovable property shall be assigned a risk weight of 100 %, where
  the conditions set out in Article 125 or 126 are not met".
- PS1/26 Art. 124H(1): "An institution shall assign a risk weight to a regulatory
  commercial real estate exposure to a natural person or SME that is not
  materially dependent on the cash-flows generated by the property as follows:
  (a) the part of the exposure up to 55% of the value of the property shall be
  assigned a risk weight of 60%; and (b) the risk weight of the counterparty shall
  be assigned to the residual part of the exposure, if any, in accordance with
  Article 124L."
- CRR Art. 164(4): the A-IRB retail exposure-weighted average LGD floor is 10%
  for exposures secured by residential property and 15% for commercial.

References:
- CRR Art. 124(1), 125, 126, 164(4); PS1/26 Art. 124F, 124H, 124L
"""

