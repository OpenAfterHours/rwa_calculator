class TestArt124h3WholeLoanUnderBasel31:
    """CL-10: the Art. 124H(3) whole loan keeps its LTV and reads the whole of Art. 124I."""

    @pytest.mark.parametrize(
        ("regime", "cqs", "prior_charge_ltv", "expected_rwa"),
        [
            # CQS 5 (150%), own 70,000 behind a 20,000 prior charge on 100,000:
            # LTV 0.9 (Art. 124C(3)), Art. 124I(3)(c) 137.5% -> 96,250.
            # Pre-fix: LTV overwritten to 0.7, counterparty read as 100% -> 70,000.
            ("b31", 5, 0.2, 96_250.0),
            # No prior charge: Art. 124I(2) 110% at LTV 0.9 -> 77,000 (pre 70,000).
            ("b31", 5, None, 77_000.0),
            # Unrated (100%): min(100%, 137.5%) binds -> 70,000, unchanged.
            ("b31", None, 0.2, 70_000.0),
            # CRR has no Art. 124H(3): the Art. 126 blend on a CQS 5 corporate,
            # not property-dependent (RE-17): 0.5 x 0.5/0.9 + 1.5 x 0.4/0.9
            # -> 66,111.11 (pre-fix Art. 124(1) 100% -> 70,000).
            ("crr", 5, 0.2, 70_000.0 * (0.5 * 0.5 / 0.9 + 1.5 * 0.4 / 0.9)),
        ],
    )
    def test_junior_charge_whole_loan(
        self, regime: str, cqs: int | None, prior_charge_ltv: float | None, expected_rwa: float
    ) -> None:
        # Arrange
        collateral = _property(100_000.0, "commercial", 0.9, prior_charge_ltv=prior_charge_ltv)

        # Act
        df = _run(regime, _CORPORATE, _loan(70_000.0, "term_loan"), collateral, cqs=cqs)

        # Assert
        assert df.height == 1
        if regime == "b31":
            assert df["re_split_role"][0] == "whole"
            assert df["ltv"][0] == pytest.approx(0.9)
        assert _total_rwa(df) == pytest.approx(expected_rwa)

    def test_rated_corporate_reaches_the_sixty_percent_floor(self) -> None:
        """CQS 1 (20%): max(60%, min(20%, 100%)) = 60% -> 240,000 (pre-fix 400,000).

        The whole-loan row is ``commercial_mortgage``, a class with no CQS table,
        so the counterparty weight was the 100% null fill whatever the rating.
        """
        # Arrange
        collateral = _property(1_000_000.0, "commercial", 0.4)

        # Act
        df = _run("b31", _CORPORATE, _loan(400_000.0, "term_loan"), collateral, cqs=1)

        # Assert
        assert df["re_split_role"][0] == "whole"
        assert df["risk_weight"][0] == pytest.approx(0.60)
        assert _total_rwa(df) == pytest.approx(240_000.0)
