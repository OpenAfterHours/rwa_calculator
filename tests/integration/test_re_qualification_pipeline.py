"""
Integration tests: real-estate qualification gates through the full pipeline
(review CL-07 / RE-09, RE-17, CL-10).

Pipeline position:
    Loader -> HierarchyResolver -> Classifier -> CRMProcessor
        -> RealEstateSplitter -> SACalculator -> Aggregator

Key responsibilities (each pinned in BOTH regimes, hand-calculated):
- CL-07 / RE-09 (CRR): a property attested ``is_qualifying_re=False`` loses the
  Art. 125 / 126 preferential weights and takes Art. 124(1) — 100% on the part
  secured up to the property value — on a whole mortgage row and on the
  loan-split secured row alike. A null attestation keeps today's weight (P1.292
  owns the null default). Basel 3.1 is the control: Art. 124J already applied.
- RE-17 (CRR, = P1.263): commercial property takes the Art. 126 50% only where
  repayment does NOT materially depend on its cash flows (collateral
  ``is_income_producing=False``); income-producing property takes Art. 124(1).
- CL-10 (Basel 3.1): the Art. 124H(3) whole-loan row keeps the Art. 124C LTV
  supplied (it includes prior charges), its cap reads the Art. 124I(3)
  junior-charge weight, and the counterparty weight in the min() is the
  obligor's Art. 122 weight by CQS rather than the 100% null fill.

Rule text relied on (verbatim):
- CRR Art. 124(1): "An exposure or any part of an exposure fully secured by
  mortgage on immovable property shall be assigned a risk weight of 100 %,
  where the conditions set out in Article 125 or 126 are not met ... The part of
  an exposure that is treated as fully secured by immovable property shall not
  be greater than the pledged amount of the market value".
- CRR Art. 126(2)(b): "the risk of the borrower shall not materially depend upon
  the performance of the underlying property or project, but on the underlying
  capacity of the borrower to repay the debt from other sources".
- PS1/26 Art. 124C(3): "The amount of the loan which is used for the calculation
  of the LTV shall include all other loans secured with charges ranking in
  priority ahead of or pari passu with the charge that the exposure is secured
  by."
- PS1/26 Art. 124H(3): "... assign a risk weight that is the higher of: (a) 60%;
  and (b) the lower of: (i) the risk weight of the counterparty in accordance
  with point (e) of Article 124L(1); and (ii) the risk weight that would be
  assigned to the exposure under Article 124I if the exposure was materially
  dependent on the cash-flows generated by the property."
- PS1/26 Art. 124I(3): "... (c) 137.5% to the whole of the exposure if the LTV
  is greater than 80%."

References:
- CRR Art. 122, 124(1), 125, 126; PS1/26 Art. 122(2), 124C, 124H(3), 124I, 124J
"""

