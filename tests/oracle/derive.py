"""
Independent oracle derivations.

This script is the SOLE programmatic source of truth for the expected RWA
values in `expected_values.json`. It uses ONLY Python stdlib (`hashlib`,
`json`, `math`, `pathlib`) plus the sibling `derivations/` package -- which is
itself stdlib-only. It DOES NOT IMPORT `rwa_calc`.

Each oracle produced by `derivations/` corresponds to a section in
`ORACLE_DERIVATIONS.md` with the same identifier (ORC-001, ORC-002, ...). The
arithmetic there must produce the same numbers shown in that document.

Run:
    uv run python tests/oracle/derive.py

Output:
    tests/oracle/expected_values.json
        Embeds a SHA-256 hash of ORACLE_DERIVATIONS.md under
        `derivations_doc_hash`. Line endings are normalised to LF before
        hashing so the hash is stable across Windows / Unix.

Regeneration is clean across interpreters:
    The standard library's normal CDF is computed differently across Python
    versions (``0.5 * (1 + erf(x))`` up to 3.13, ``0.5 * erfc(-x)`` from 3.14),
    so the IRB conditional PDs -- and the risk weights and RWAs built on them --
    move in their last bits between the two interpreter families, and a file
    committed from one family drifts on the other. A plain rewrite would then
    show untouched records as changed. So when a committed file exists, every
    float leaf whose fresh value is within ``FLOAT_NOISE_RELATIVE`` (relative)
    of the committed one keeps the committed bytes; every other difference --
    a real value move, any non-float leaf, an added or removed record or key, a
    reordering -- is written as computed. The script prints how many leaves it
    kept, so a regeneration always says what it suppressed. ``test_derive.py``
    pins that regenerating the committed file reproduces it exactly under
    either CDF form.
"""

from __future__ import annotations

import hashlib
import json
import math
import sys
from collections import Counter
from pathlib import Path
from typing import Any

# Run as a script (`uv run python tests/oracle/derive.py`), sys.path[0] is this
# directory rather than the repo root, so the package import below would fail.
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from tests.oracle.derivations import all_oracles  # noqa: E402

HERE = Path(__file__).parent
DOC_PATH = HERE / "ORACLE_DERIVATIONS.md"
JSON_PATH = HERE / "expected_values.json"

#: The relative difference at or below which a fresh float is float noise, not
#: a change, and the committed value is kept.
#:
#: Sized from the mechanism, not from one measurement. The erf-form CDF can only
#: return values on a grid of 2**-54 (about 5.6e-17) below 0.25, so k steps of
#: that grid are a relative move of about k * 5.6e-17 / p at conditional PD p,
#: and the risk weight and RWA built on it move by about the same relative
#: amount. At the smallest conditional PD the oracle publishes (about 0.0058)
#: that is about k * 1e-14, so this threshold absorbs ~100 grid steps there; the
#: drift measured between interpreter families is at most 2.4e-15 relative
#: (under one step). It sits six orders of magnitude below the 1e-6 tolerance
#: the oracle tests compare at, so no correction that tolerance could ever see
#: is swallowed -- ``test_derive.py`` fails if it is loosened to within 1e5x of
#: that tolerance.
FLOAT_NOISE_RELATIVE = 1e-12

_DOC_NOTE = (
    "Generated by tests/oracle/derive.py. Do NOT hand-edit. "
    "To change values, edit ORACLE_DERIVATIONS.md and the "
    "tests/oracle/derivations/ modules together, then re-run derive.py."
)


def main() -> None:
    """Regenerate ``expected_values.json`` and report what was written and kept."""
    payload, preserved = regenerate(JSON_PATH)
    oracles = payload["oracles"]

    by_phase = Counter(o["phase"] for o in oracles)
    by_framework = Counter(o["framework"] for o in oracles)
    print(f"Wrote {JSON_PATH.name} with {len(oracles)} oracle exposures.")
    print(f"  by phase:     {dict(sorted(by_phase.items()))}")
    print(f"  by framework: {dict(sorted(by_framework.items()))}")
    print(
        f"  float noise:  kept {preserved} committed leaf value(s) whose fresh value "
        f"differed by <= {FLOAT_NOISE_RELATIVE:g} relative"
    )
    print(f"Derivations doc hash: {payload['derivations_doc_hash']}")


def regenerate(json_path: Path) -> tuple[dict[str, Any], int]:
    """Rebuild ``json_path`` from the derivations, splicing against what it holds.

    A missing or unparsable file (a merge conflict, say) is treated as having no
    committed values, so every value is written as computed.

    Returns:
        The payload written and the number of committed float leaves kept.
    """
    payload, preserved = build_payload(_read_committed(json_path))
    json_path.write_text(render(payload))
    return payload, preserved


def build_payload(committed: dict[str, Any] | None) -> tuple[dict[str, Any], int]:
    """The payload ``derive.py`` writes, given the currently committed one (if any).

    Pure: reads the derivations and the doc hash, writes nothing.

    Returns:
        The payload and the number of committed float leaves kept as float noise.
    """
    oracles = all_oracles()
    preserved = 0
    if committed is not None:
        oracles, preserved = splice_float_noise(committed.get("oracles", []), oracles)
    payload = {
        "_doc": _DOC_NOTE,
        "derivations_doc": "ORACLE_DERIVATIONS.md",
        "derivations_doc_hash_algorithm": "sha256-lf-normalised",
        "derivations_doc_hash": doc_hash(),
        "tolerance_relative": 1e-6,
        "tolerance_absolute_minor": 0.01,
        "oracles": oracles,
    }
    return payload, preserved


def splice_float_noise(
    committed: list[dict[str, Any]],
    fresh: list[dict[str, Any]],
) -> tuple[list[dict[str, Any]], int]:
    """Fresh oracle records, with float noise against the committed ones undone.

    Records are matched by ``exposure_id``; the fresh list decides which records
    exist and in what order. Within a matched record, dicts follow the fresh
    keys and key order, and equal-length lists are walked element by element. A
    leaf keeps its committed value only when both values are ``float`` (never
    ``bool`` or ``int``) and differ by at most ``FLOAT_NOISE_RELATIVE`` of the
    larger magnitude; anything else takes the fresh value.

    Returns:
        The spliced records and the number of leaves whose committed text was
        kept over a different fresh text.
    """
    by_id = {record.get("exposure_id"): record for record in committed}
    spliced: list[dict[str, Any]] = []
    preserved = 0
    for record in fresh:
        previous = by_id.get(record["exposure_id"])
        if previous is None:
            spliced.append(record)
            continue
        merged, kept = _merge(previous, record)
        spliced.append(merged)
        preserved += kept
    return spliced, preserved


def render(payload: dict[str, Any]) -> str:
    """The exact text written to ``expected_values.json``."""
    return json.dumps(payload, indent=2) + "\n"


def doc_hash() -> str:
    """SHA-256 of the derivations doc, with line endings normalised to LF.

    The normalisation makes the hash stable across CRLF (Windows) and LF
    (Unix) checkouts.
    """
    raw = DOC_PATH.read_bytes().replace(b"\r\n", b"\n")
    return hashlib.sha256(raw).hexdigest()


def _read_committed(json_path: Path) -> dict[str, Any] | None:
    """The committed payload, or ``None`` when there is none to splice against."""
    try:
        committed = json.loads(json_path.read_text())
    except (FileNotFoundError, json.JSONDecodeError):
        return None
    return committed if isinstance(committed, dict) else None


def _merge(committed: Any, fresh: Any) -> tuple[Any, int]:
    """``fresh``, with committed float leaves kept where the move is float noise."""
    if isinstance(committed, dict) and isinstance(fresh, dict):
        merged: dict[str, Any] = {}
        kept = 0
        for key, value in fresh.items():
            if key not in committed:
                merged[key] = value
                continue
            merged[key], count = _merge(committed[key], value)
            kept += count
        return merged, kept
    if isinstance(committed, list) and isinstance(fresh, list) and len(committed) == len(fresh):
        items: list[Any] = []
        kept = 0
        for old, new in zip(committed, fresh, strict=True):
            item, count = _merge(old, new)
            items.append(item)
            kept += count
        return items, kept
    if _is_float_noise(committed, fresh):
        return committed, int(repr(committed) != repr(fresh))
    return fresh, 0


def _is_float_noise(committed: Any, fresh: Any) -> bool:
    """Both are finite ``float`` and within ``FLOAT_NOISE_RELATIVE`` of each other."""
    if type(committed) is not float or type(fresh) is not float:
        return False
    if not (math.isfinite(committed) and math.isfinite(fresh)):
        return False
    return abs(committed - fresh) <= FLOAT_NOISE_RELATIVE * max(abs(committed), abs(fresh))


if __name__ == "__main__":
    main()
