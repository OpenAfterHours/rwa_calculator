"""
Unit tests: the Art. 124E(1)(a) primary-residence carrier and its classifier use (P1.473).

Pipeline position:
    Loader -> HierarchyResolver (engine/hierarchy/enrich.py) -> ExposureClassifier
    (engine/classify/attributes.py) -> CRMProcessor

Key responsibilities pinned here:
- ``enrich.enrich_with_property_coverage`` sets ``re_collateral_is_primary_residence``
  only where the exposure is secured by exactly ONE real-estate collateral row,
  across the direct / facility / counterparty levels, and that row is flagged
  ``is_primary_residence`` True. Two pledged properties are never "a single
  property", whichever of them is flagged and at whichever level; null is not
  an attestation.
- The classifier's Art. 124E(2) count re-route (``has_income_cover``) spares such
  an exposure, never overrides an explicit income flag, and is never null.

Rule text (PS1/26 Art. 124E(1), verbatim): "A residential real estate exposure is
materially dependent on the cash-flows generated by the property unless it is:
(a) to one or more natural persons and the exposure is secured by a single property
that is the obligor's primary residence; (b) to one or more natural persons that
individually meet the three property limit in accordance with paragraph 2; ..."
Art. 124E(4): "each separate housing unit shall count as an individual property".

References:
- PS1/26 Art. 124E(1)(a)/(b), (2), (4)
- IMPLEMENTATION_PLAN.md: P1.473 (review RE-18)
"""

from __future__ import annotations

from datetime import date
from typing import Any

import polars as pl
import pytest

from rwa_calc.contracts.config import CalculationConfig
from rwa_calc.engine.classify import ExposureClassifier
from rwa_calc.engine.hierarchy import HierarchyResolver
from tests.fixtures.raw_bundle import make_raw_bundle

_REPORTING_DATE = date(2027, 3, 31)


def _cp(ref: str, *, count: int | None, natural_person: bool = True) -> dict[str, Any]:
    return {
        "counterparty_reference": ref,
        "counterparty_name": ref,
        "entity_type": "individual" if natural_person else "corporate",
        "country_code": "GB",
        "default_status": False,
        "is_natural_person": natural_person,
        "qualifying_property_count": count,
    }


def _loan(ref: str, cp: str = "CP1") -> dict[str, Any]:
    return {
        "loan_reference": ref,
        "product_type": "mortgage",
        "book_code": "B",
        "counterparty_reference": cp,
        "value_date": date(2024, 1, 1),
        "maturity_date": date(2045, 1, 1),
        "currency": "GBP",
        "drawn_amount": 60_000.0,
        "interest": 0.0,
        "seniority": "senior",
    }


def _property(
    ref: str, level: str, beneficiary: str, primary: bool | None, **extra: Any
) -> dict[str, Any]:
    return {
        "collateral_reference": ref,
        "collateral_type": "real_estate",
        "currency": "GBP",
        "market_value": 100_000.0,
        "beneficiary_type": level,
        "beneficiary_reference": beneficiary,
        "property_type": "residential",
        "property_ltv": 0.6,
        "is_primary_residence": primary,
        **extra,
    }


def _frame(rows: list[dict[str, Any]]) -> pl.DataFrame:
    keys: list[str] = []
    for row in rows:
        keys.extend(k for k in row if k not in keys)
    return pl.DataFrame({k: [row.get(k) for row in rows] for k in keys}, strict=False)


def _bundle(
    loans: list[dict[str, Any]],
    collateral: list[dict[str, Any]] | None,
    counterparties: list[dict[str, Any]] | None = None,
    *,
    facilities: list[dict[str, Any]] | None = None,
    mappings: list[dict[str, Any]] | None = None,
) -> Any:
    kwargs: dict[str, Any] = {}
    if collateral is not None:
        kwargs["collateral"] = _frame(collateral)
    if facilities is not None:
        kwargs["facilities"] = _frame(facilities)
    return make_raw_bundle(
        counterparties=_frame(counterparties or [_cp("CP1", count=4)]),
        loans=_frame(loans),
        facility_mappings=_frame(mappings)
        if mappings
        else pl.DataFrame(
            schema={
                "parent_facility_reference": pl.String,
                "child_reference": pl.String,
                "child_type": pl.String,
            }
        ),
        **kwargs,
    )


def _config(regime: str) -> CalculationConfig:
    if regime == "b31":
        return CalculationConfig.basel_3_1(reporting_date=_REPORTING_DATE)
    return CalculationConfig.crr(reporting_date=_REPORTING_DATE)


def _resolved(bundle: Any, regime: str = "b31") -> pl.DataFrame:
    return HierarchyResolver().resolve(bundle, _config(regime)).exposures.collect()


def _classified(bundle: Any, regime: str) -> pl.DataFrame:
    config = _config(regime)
    resolved = HierarchyResolver().resolve(bundle, config)
    return ExposureClassifier().classify(resolved, config).all_exposures.collect()


def _row(df: pl.DataFrame, ref: str) -> dict[str, Any]:
    rows = df.filter(pl.col("exposure_reference") == ref)
    assert rows.height == 1, f"{ref} not emitted once: {df['exposure_reference'].to_list()}"
    return rows.row(0, named=True)


class TestPrimaryResidenceCarrier:
    """``re_collateral_is_primary_residence``: exactly one linked property, flagged True."""

    @pytest.mark.parametrize(("flag", "expected"), [(True, True), (False, False), (None, False)])
    def test_single_direct_property_carries_its_flag(
        self, flag: bool | None, expected: bool
    ) -> None:
        # Act
        df = _resolved(_bundle([_loan("L1")], [_property("P1", "loan", "L1", flag)]))

        # Assert
        assert _row(df, "L1")["re_collateral_is_primary_residence"] is expected

    @pytest.mark.parametrize("property_type", ["commercial", None], ids=["commercial", "untyped"])
    def test_flagged_non_residential_property_is_not_limb_a(
        self, property_type: str | None
    ) -> None:
        """A flagged commercial (or untyped) property: Art. 124E(1)(a) is a residential test.

        A commercial exposure is decided by Art. 124E(6) — materially dependent unless
        each property is "predominantly used by the borrower for its own business
        purpose" — and a home is not a business use, so the flag grants nothing.
        """
        # Arrange
        pledge = _property("P1", "loan", "L1", True, property_type=property_type)

        # Act
        df = _resolved(_bundle([_loan("L1")], [pledge]))

        # Assert
        assert _row(df, "L1")["re_collateral_is_primary_residence"] is False

    @pytest.mark.parametrize(
        "flags", [(True, False), (False, True), (True, None), (True, True)], ids=str
    )
    def test_two_properties_on_one_loan_are_not_a_single_property(
        self, flags: tuple[bool | None, bool | None]
    ) -> None:
        """Home + buy-to-let (either order), or two flagged homes: never limb (a)."""
        # Arrange
        pledges = [_property(f"P{i}", "loan", "L1", flag) for i, flag in enumerate(flags)]

        # Act
        df = _resolved(_bundle([_loan("L1")], pledges))

        # Assert
        assert _row(df, "L1")["re_collateral_is_primary_residence"] is False

    def test_properties_at_two_levels_are_not_a_single_property(self) -> None:
        """A flagged loan-level home plus a flagged counterparty-level property: two properties."""
        # Arrange
        pledges = [
            _property("P1", "loan", "L1", True),
            _property("P2", "counterparty", "CP1", True),
        ]

        # Act
        df = _resolved(_bundle([_loan("L1")], pledges))

        # Assert
        assert _row(df, "L1")["re_collateral_is_primary_residence"] is False

    def test_counterparty_pledge_of_the_home_reaches_each_exposure(self) -> None:
        """One flagged home pledged at counterparty level is each loan's single property."""
        # Act
        df = _resolved(
            _bundle([_loan("L1"), _loan("L2")], [_property("P1", "counterparty", "CP1", True)])
        )

        # Assert
        assert _row(df, "L1")["re_collateral_is_primary_residence"] is True
        assert _row(df, "L2")["re_collateral_is_primary_residence"] is True

    def test_facility_pledge_of_the_home_reaches_the_drawn_loan(self) -> None:
        """A flagged home pledged to the parent facility is the loan's single property."""
        # Arrange
        facility = {
            "facility_reference": "F1",
            "product_type": "mortgage",
            "book_code": "B",
            "counterparty_reference": "CP1",
            "value_date": date(2024, 1, 1),
            "maturity_date": date(2045, 1, 1),
            "currency": "GBP",
            "limit": 60_000.0,
            "committed": True,
            "seniority": "senior",
            "risk_type": "MR",
        }
        mapping = {"parent_facility_reference": "F1", "child_reference": "L1", "child_type": "loan"}

        # Act
        df = _resolved(
            _bundle(
                [_loan("L1")],
                [_property("P1", "facility", "F1", True)],
                facilities=[facility],
                mappings=[mapping],
            )
        )

        # Assert
        assert _row(df, "L1")["re_collateral_is_primary_residence"] is True

    def test_no_property_is_no_attestation(self) -> None:
        # Act
        df = _resolved(_bundle([_loan("L1")], None))

        # Assert
        assert _row(df, "L1")["re_collateral_is_primary_residence"] is False

    def test_non_real_estate_collateral_does_not_count_as_a_property(self) -> None:
        """Cash beside the flagged home leaves the home the single property."""
        # Arrange
        pledges = [
            _property("P1", "loan", "L1", True),
            {
                "collateral_reference": "C1",
                "collateral_type": "cash",
                "currency": "GBP",
                "market_value": 1_000.0,
                "beneficiary_type": "loan",
                "beneficiary_reference": "L1",
            },
        ]

        # Act
        df = _resolved(_bundle([_loan("L1")], pledges))

        # Assert
        assert _row(df, "L1")["re_collateral_is_primary_residence"] is True


class TestCountReRouteSparesThePrimaryResidence:
    """``has_income_cover`` after the classifier: Art. 124E(1)(a) beside the (b) re-route."""

    @pytest.mark.parametrize(
        ("count", "flag", "income", "natural_person", "expected"),
        [
            (4, True, None, True, False),  # over the limit, single attested home: (a) holds
            (4, False, None, True, True),  # over the limit, buy-to-let: re-routed
            (4, None, None, True, True),  # over the limit, not attested: re-routed
            (4, True, True, True, True),  # explicit income-producing flag stands
            (3, False, None, True, False),  # within the limit: (b) holds
            (None, False, None, True, False),  # count unknown: no re-route, and never null
            (9, False, None, False, False),  # not a natural person: no count re-route
        ],
        ids=[
            "home_over_limit",
            "btl_over_limit",
            "unattested_over_limit",
            "explicit_income",
            "within_limit",
            "unknown_count",
            "not_natural_person",
        ],
    )
    def test_b31_truth_table(
        self,
        count: int | None,
        flag: bool | None,
        income: bool | None,
        natural_person: bool,
        expected: bool,
    ) -> None:
        # Arrange
        bundle = _bundle(
            [_loan("L1")],
            [_property("P1", "loan", "L1", flag, is_income_producing=income)],
            [_cp("CP1", count=count, natural_person=natural_person)],
        )

        # Act
        row = _row(_classified(bundle, "b31"), "L1")

        # Assert
        assert row["has_income_cover"] is expected

    def test_flagged_commercial_home_over_limit_stays_re_routed(self) -> None:
        """A commercial-typed property flagged as the home is not spared: Art. 124E(6) decides."""
        # Arrange
        pledge = _property("P1", "loan", "L1", True, property_type="commercial")
        bundle = _bundle([_loan("L1")], [pledge], [_cp("CP1", count=4)])

        # Act
        row = _row(_classified(bundle, "b31"), "L1")

        # Assert
        assert row["has_income_cover"] is True

    @pytest.mark.parametrize("flag", [True, False, None])
    def test_crr_has_no_count_re_route(self, flag: bool | None) -> None:
        """CRR: the Feature is off, so the flag and the count change nothing."""
        # Arrange
        bundle = _bundle([_loan("L1")], [_property("P1", "loan", "L1", flag)])

        # Act
        row = _row(_classified(bundle, "crr"), "L1")

        # Assert
        assert row["has_income_cover"] is False
