"""
Unit tests: the CRR real-estate qualification gates (review CL-07 / RE-09, RE-17).

Pipeline position:
    CRMProcessor -> SACalculator (engine/sa/risk_weights.py::
    _crr_append_real_estate_branches, engine/sa/crr_real_estate.py)

Key responsibilities pinned here:
- CL-07 / RE-09: an explicit ``is_qualifying_re=False`` under CRR loses the
  Art. 125 / Art. 126 preferential weights and takes Art. 124(1): 100% on the
  part secured up to the property value, the counterparty's unsecured weight on
  any excess. A null attestation keeps today's behaviour (the null default is
  the separate open item P1.292). The Art. 127(3) 100% defaulted-RRE weight
  ("secured ... in accordance with Article 125") is withheld the same way.
- RE-17 (= P1.263): the Art. 126 50% weight is granted only where the risk of
  the borrower does NOT materially depend on the property's cash flows
  (``has_income_cover=False``). The gate was inverted: income-producing CRE took
  50% and owner-occupied CRE 100%.
- P1.315: a defaulted commercial exposure that meets the same Art. 126 test
  takes the Art. 127(4) 100% on its Art. 126(2)(d) secured share
  (``min(1, 0.50 / ltv)``) and the Art. 127(1) provision weight on the rest. It
  took the provision weight (150% with no provisions) on the whole row. Basel
  3.1 has no such limb: PS1/26 Art. 127(3) covers residential property only.

Rule text (verbatim, UK CRR as onshored):
- Art. 124(1): "An exposure or any part of an exposure fully secured by mortgage
  on immovable property shall be assigned a risk weight of 100 %, where the
  conditions set out in Article 125 or 126 are not met, except for any part of
  the exposure which is assigned to another exposure class. The part of the
  exposure that exceeds the mortgage value of the immovable property shall be
  assigned the risk weight applicable to the unsecured exposures of the
  counterparty involved. The part of an exposure that is treated as fully
  secured by immovable property shall not be greater than the pledged amount of
  the market value ..."
- Art. 125(2) / 126(2): "Institutions shall consider an exposure or any part of
  an exposure as fully and completely secured for the purposes of paragraph 1
  only if the following conditions are met: ... (c) the requirements set out in
  Article 208 and the valuation rules set out in Article 229(1) are met".
- Art. 126(2)(b): "the risk of the borrower shall not materially depend upon the
  performance of the underlying property or project, but on the underlying
  capacity of the borrower to repay the debt from other sources, and as a
  consequence, the repayment of the facility shall not materially depend on any
  cash flow generated by the underlying property serving as collateral".
- Art. 127(3): "The exposure value remaining after specific credit risk
  adjustments of exposures fully and completely secured by mortgages on
  residential property in accordance with Article 125 shall be assigned a risk
  weight of 100 % if a default has occurred".
- Art. 127(4): "The exposure value remaining after specific credit risk
  adjustments of exposures fully and completely secured by mortgages on
  commercial immovable property in accordance with Article 126 shall be assigned
  a risk weight of 100 % if a default has occurred in accordance with Article
  178."
- PS1/26 Art. 127(3) (the Basel 3.1 control): "A residential real estate
  exposure which is a defaulted exposure and is not materially dependent on the
  cash-flows of the property shall be assigned a risk weight of 100%." There is
  no commercial paragraph.

References:
- CRR Art. 124(1), 125(2), 126(2)(b), 126(2)(d), 127(3), 127(4)
- PRA Rulebook, Credit Risk Part, rules 4.1 / 4.1A (to 31 December 2026)
- PS1/26 Art. 124J, 124L, 127 (the Basel 3.1 controls)
"""

from __future__ import annotations

from datetime import date
from decimal import Decimal

import pytest
from tests.fixtures.single_exposure import calculate_single_sa_exposure

from rwa_calc.contracts.config import CalculationConfig
from rwa_calc.engine.sa import SACalculator


@pytest.fixture
def sa_calculator() -> SACalculator:
    return SACalculator()


def _config(regime: str) -> CalculationConfig:
    if regime == "b31":
        return CalculationConfig.basel_3_1(reporting_date=date(2027, 3, 31))
    return CalculationConfig.crr(reporting_date=date(2026, 12, 31))


def _rw(sa_calculator: SACalculator, regime: str, **kwargs: object) -> float:
    result = calculate_single_sa_exposure(
        sa_calculator, ead=Decimal("100000"), config=_config(regime), **kwargs
    )
    return float(result["risk_weight"])


_NP_MORTGAGE: dict[str, object] = {
    "exposure_class": "retail_mortgage",
    "property_type": "residential",
    "cp_is_natural_person": True,
    "qualifies_as_retail": True,
}


class TestCrrResidentialQualificationGate:
    """CL-07 / RE-09: explicit ``is_qualifying_re=False`` -> CRR Art. 124(1)."""

    @pytest.mark.parametrize(
        ("is_qualifying_re", "expected_rw"),
        [
            # Art. 124(1): conditions of Art. 125 not met -> 100% on the whole
            # loan (LTV 0.4: the loan is inside the property value). Pre-fix 0.35.
            (False, 1.00),
            # Attested qualifying and the unreported null keep Art. 125's 35%.
            (True, 0.35),
            (None, 0.35),
        ],
    )
    def test_explicit_false_loses_the_art_125_weight(
        self, sa_calculator: SACalculator, is_qualifying_re: bool | None, expected_rw: float
    ) -> None:
        # Act
        rw = _rw(
            sa_calculator,
            "crr",
            ltv=Decimal("0.40"),
            is_qualifying_re=is_qualifying_re,
            **_NP_MORTGAGE,
        )

        # Assert
        assert rw == pytest.approx(expected_rw)

    def test_explicit_false_above_the_property_value_blends_the_counterparty_weight(
        self, sa_calculator: SACalculator
    ) -> None:
        """LTV 1.5: 100% on the part up to the value, Art. 123 75% on the excess.

        1.00 x (1 / 1.5) + 0.75 x (0.5 / 1.5) = 0.666667 + 0.25 = 0.916667.
        Pre-fix: the Art. 125 blend, 0.35 x 0.8/1.5 + 0.75 x 0.7/1.5 = 0.536667.
        """
        # Act
        rw = _rw(sa_calculator, "crr", ltv=Decimal("1.50"), is_qualifying_re=False, **_NP_MORTGAGE)

        # Assert
        assert rw == pytest.approx(1.0 / 1.5 + 0.75 * 0.5 / 1.5)

    def test_basel_3_1_explicit_false_unchanged(self, sa_calculator: SACalculator) -> None:
        """Control: Basel 3.1 explicit False stays Art. 124J(2) -> Art. 124L(a) 75%."""
        # Act
        rw = _rw(sa_calculator, "b31", ltv=Decimal("0.40"), is_qualifying_re=False, **_NP_MORTGAGE)

        # Assert
        assert rw == pytest.approx(0.75)

    @pytest.mark.parametrize(
        ("is_qualifying_re", "expected_rw"),
        [
            # Not secured "in accordance with Article 125": Art. 127(3) does not
            # apply, so the Art. 127(1) unsecured weight governs — 150% with no
            # specific credit risk adjustment. Pre-fix: the Art. 127(3) 100%.
            (False, 1.50),
            (True, 1.00),
        ],
    )
    def test_defaulted_art_127_3_needs_the_art_125_conditions(
        self, sa_calculator: SACalculator, is_qualifying_re: bool, expected_rw: float
    ) -> None:
        # Act
        rw = _rw(
            sa_calculator,
            "crr",
            ltv=Decimal("0.50"),
            is_defaulted=True,
            is_qualifying_re=is_qualifying_re,
            **_NP_MORTGAGE,
        )

        # Assert
        assert rw == pytest.approx(expected_rw)

    @pytest.mark.parametrize(
        ("is_qualifying_re", "expected_rw"),
        # Commercial property, not materially dependent, LTV 0.4: Art. 126(1)(a)
        # 50% only when attested; Art. 124(1) 100% when explicitly not, and
        # when unreported — PRA Credit Risk Part rule 4.1 / 4.1A (to 31 Dec 2026)
        # admit Art. 126 for commercial property only where a loss condition on
        # PRA market data is met, which a null does not show.
        [(False, 1.00), (True, 0.50), (None, 1.00)],
    )
    def test_commercial_explicit_false_loses_the_art_126_weight(
        self, sa_calculator: SACalculator, is_qualifying_re: bool | None, expected_rw: float
    ) -> None:
        # Act
        rw = _rw(
            sa_calculator,
            "crr",
            exposure_class="commercial_mortgage",
            property_type="commercial",
            ltv=Decimal("0.40"),
            has_income_cover=False,
            is_qualifying_re=is_qualifying_re,
        )

        # Assert
        assert rw == pytest.approx(expected_rw)


class TestCrrArt126MaterialDependenceGate:
    """RE-17 / P1.263: Art. 126's 50% only where NOT materially dependent."""

    @pytest.mark.parametrize(
        ("has_income_cover", "expected_rw", "pre_fix_rw"),
        [
            # Owner-occupied (repayment from other sources): Art. 126(1)(a) 50%.
            (False, 0.50, 1.00),
            # Repayment materially depends on the property's cash flows:
            # Art. 126(2)(b) fails -> Art. 124(1) 100% (LTV 0.4 < 1).
            (True, 1.00, 0.50),
        ],
    )
    def test_fifty_percent_requires_no_material_dependence(
        self,
        sa_calculator: SACalculator,
        has_income_cover: bool,
        expected_rw: float,
        pre_fix_rw: float,
    ) -> None:
        # Act
        rw = _rw(
            sa_calculator,
            "crr",
            exposure_class="commercial_mortgage",
            property_type="commercial",
            ltv=Decimal("0.40"),
            has_income_cover=has_income_cover,
            is_qualifying_re=True,
        )

        # Assert
        assert rw == pytest.approx(expected_rw)
        assert rw != pytest.approx(pre_fix_rw)

    def test_adc_lending_never_meets_art_126_2_b(self, sa_calculator: SACalculator) -> None:
        """Commercial ADC, income flag False: still Art. 124(1) 100%, not 50%.

        Art. 126(2)(b) needs "the risk of the borrower shall not materially depend
        upon the performance of the underlying property or project" — development
        finance depends on the project by definition. Without this guard the
        RE-17 fix would have handed a commercial ADC loan the 50%.
        """
        # Act
        rw = _rw(
            sa_calculator,
            "crr",
            exposure_class="corporate",
            property_type="commercial",
            ltv=Decimal("0.40"),
            has_income_cover=False,
            is_adc=True,
            qualifies_as_retail=False,
        )

        # Assert
        assert rw == pytest.approx(1.00)

    def test_not_dependent_above_fifty_percent_ltv_blends(
        self, sa_calculator: SACalculator
    ) -> None:
        """LTV 0.8, unrated corporate: 0.50 x 0.5/0.8 + 1.00 x 0.3/0.8 = 0.6875."""
        # Act
        rw = _rw(
            sa_calculator,
            "crr",
            exposure_class="corporate",
            property_type="commercial",
            ltv=Decimal("0.80"),
            has_income_cover=False,
            qualifies_as_retail=False,
            is_qualifying_re=True,
        )

        # Assert
        assert rw == pytest.approx(0.50 * 0.5 / 0.8 + 1.00 * 0.3 / 0.8)

    def test_dependent_above_the_property_value_blends_the_counterparty_weight(
        self, sa_calculator: SACalculator
    ) -> None:
        """Income-producing, CQS 1 corporate (20%), LTV 1.25: Art. 124(1).

        100% on the part up to the property value (0.8 of the loan) and the
        corporate's unsecured CQS 1 20% on the excess: 0.8 + 0.2 x 0.2 = 0.84.
        """
        # Act
        rw = _rw(
            sa_calculator,
            "crr",
            exposure_class="corporate",
            property_type="commercial",
            cqs=1,
            ltv=Decimal("1.25"),
            has_income_cover=True,
            qualifies_as_retail=False,
        )

        # Assert
        assert rw == pytest.approx(1.00 * 0.8 + 0.20 * 0.2)

    def test_basel_3_1_income_producing_unchanged(self, sa_calculator: SACalculator) -> None:
        """Control: Basel 3.1 materially-dependent CRE stays Art. 124I(1) 100%."""
        # Act
        rw = _rw(
            sa_calculator,
            "b31",
            exposure_class="commercial_mortgage",
            property_type="commercial",
            ltv=Decimal("0.40"),
            has_income_cover=True,
        )

        # Assert
        assert rw == pytest.approx(1.00)


# A defaulted commercial-property row that meets the Art. 126 test: attested
# (rule 4.1 / 4.1A), repayment not dependent on the property's cash flows, not
# ADC, no provisions. The shapes are the classes such a row carries: the
# splitter skips defaulted rows (re_split/flagging.py), so a defaulted loan
# arrives whole, classed by its obligor, with ``property_type`` naming the
# property.
_DEFAULTED_CRE: dict[str, object] = {
    "property_type": "commercial",
    "is_defaulted": True,
    "has_income_cover": False,
    "is_qualifying_re": True,
}

_CRE_SHAPES: dict[str, dict[str, object]] = {
    "commercial_mortgage": {"exposure_class": "commercial_mortgage", "qualifies_as_retail": False},
    # Production shape: a corporate term loan on commercial property.
    "corporate": {"exposure_class": "corporate", "qualifies_as_retail": False},
    # Production shape: a natural person's commercial mortgage. The class also
    # matches the residential predicate, so a gate written as "commercial and
    # not residential" would drop it.
    "retail_mortgage": {
        "exposure_class": "retail_mortgage",
        "cp_is_natural_person": True,
        "qualifies_as_retail": True,
    },
}


class TestCrrArt127_4DefaultedCommercialProperty:
    """P1.315: CRR Art. 127(4) 100% on the Art. 126-secured share of a default."""

    @pytest.mark.parametrize("shape", list(_CRE_SHAPES))
    @pytest.mark.parametrize(
        ("ltv", "expected_rw"),
        [
            # Art. 126(2)(d) secures the part up to 50% of the value: share
            # 0.5 / 0.8 = 0.625 at Art. 127(4) 100%, the other 0.375 unsecured
            # at Art. 127(1)(a) 150% (no provisions). Pre-fix 1.50.
            (Decimal("0.80"), 0.625 * 1.00 + 0.375 * 1.50),
            # LTV 0.4: the cap covers the whole loan -> 100%. Pre-fix 1.50.
            (Decimal("0.40"), 1.00),
        ],
        ids=["ltv0.8", "ltv0.4"],
    )
    def test_secured_share_takes_one_hundred_percent(
        self, sa_calculator: SACalculator, shape: str, ltv: Decimal, expected_rw: float
    ) -> None:
        # Arrange
        kwargs: dict = {**_DEFAULTED_CRE, **_CRE_SHAPES[shape], "ltv": ltv}

        # Act
        result = calculate_single_sa_exposure(
            sa_calculator, ead=Decimal("1000000"), config=_config("crr"), **kwargs
        )

        # Assert
        assert float(result["risk_weight"]) == pytest.approx(expected_rw)
        assert float(result["rwa"]) == pytest.approx(1_000_000.0 * expected_rw)

    @pytest.mark.parametrize("shape", ["corporate", "retail_mortgage"])
    @pytest.mark.parametrize(
        "failed_condition",
        [
            # PRA rule 4.1 / 4.1A not shown: a null attestation does not show
            # the loss condition, so the row is not secured "in accordance with
            # Article 126" (the residential limb's null-tolerant gate is wrong here).
            {"is_qualifying_re": None},
            {"is_qualifying_re": False},
            # Art. 126(2)(b): repayment materially depends on the property.
            {"has_income_cover": True},
            # ADC lending depends on the project.
            {"is_adc": True},
            # No usable LTV: no defensible secured share.
            {"ltv": None},
            {"ltv": Decimal("0")},
        ],
        ids=[
            "attestation_null",
            "attestation_false",
            "income_dependent",
            "adc",
            "ltv_null",
            "ltv_zero",
        ],
    )
    def test_not_secured_in_accordance_with_art_126_stays_on_art_127_1(
        self, sa_calculator: SACalculator, shape: str, failed_condition: dict[str, object]
    ) -> None:
        # Arrange
        kwargs: dict = {
            **_DEFAULTED_CRE,
            **_CRE_SHAPES[shape],
            "ltv": Decimal("0.80"),
            **failed_condition,
        }

        # Act
        rw = _rw(sa_calculator, "crr", **kwargs)

        # Assert: Art. 127(1)(a) 150% on the whole row (no provisions).
        assert rw == pytest.approx(1.50)

    def test_provisions_of_twenty_percent_put_the_unsecured_part_at_one_hundred(
        self, sa_calculator: SACalculator
    ) -> None:
        """30,000 of provisions on a 130,000 pre-provision loan: Art. 127(1)(b).

        23% is "no less than 20 %", so the unsecured part takes 100% as well as
        the Art. 127(4) secured share, and the blend is 1.00 whatever the share.
        """
        # Act
        rw = _rw(
            sa_calculator,
            "crr",
            ltv=Decimal("0.80"),
            provision_allocated=Decimal("30000"),
            provision_deducted=Decimal("30000"),
            **_DEFAULTED_CRE,
            **_CRE_SHAPES["corporate"],
        )

        # Assert
        assert rw == pytest.approx(1.00)

    @pytest.mark.parametrize("shape", list(_CRE_SHAPES))
    def test_basel_3_1_has_no_commercial_limb(
        self, sa_calculator: SACalculator, shape: str
    ) -> None:
        """Control: PS1/26 Art. 127 has no commercial paragraph -> Art. 127(1) 150%.

        The positive CRR shape (attested, not dependent, LTV 0.8, no provisions),
        so a commercial limb leaking into the Basel 3.1 branch would move it.
        """
        # Act
        rw = _rw(sa_calculator, "b31", ltv=Decimal("0.80"), **_DEFAULTED_CRE, **_CRE_SHAPES[shape])

        # Assert
        assert rw == pytest.approx(1.50)
