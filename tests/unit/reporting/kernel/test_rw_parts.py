"""
Unit tests: a loan-split real-estate row is reported against its two risk weights.

PS1/26 Annex II, OF 07.00 rows 0140-0280 (ps1-26-annex-ii-reporting-instructions.pdf
p.94): "Real estate exposures classified as regulatory real estate (residential or
commercial) which are not materially dependent on the cash flows generated by the
property (Articles 124F and 124H ...) shall be reported in two parts, against the
risk weight applied to the portion up to 55% of the value of the property, and
against the portion above 55% of the value of the property (if applicable)." And,
same page: "Exposures subject to the currency mismatch multiplier (Article 123B
...) shall be reported against the risk weight which would have applied if the
currency mismatch multiplier was not applied. However, the RWEA shall still
reflect the currency mismatch multiplier."

``split_risk_weight_parts`` turns a row whose reported weight is still the
engine's recorded two-part weight into two rows. Pinned here:

- conservation: the two parts of every exposure and RWEA column sum to the row;
- the parts carry their own weights, so they band on published rows;
- a row whose weight has since moved (a guaranteed leg, a defaulted leg) is left
  whole, because its reported weight is no longer the two-part one;
- an Art. 123B row is recognised on its pre-multiplier weight and split at the
  un-multiplied part weights while its RWEA keeps the multiplier;
- NULL and ABSENT carriers are different code paths (LESSONS B1), both no-ops.

References:
- src/rwa_calc/reporting/kernel/rw_parts.py
- PS1/26 Art. 123B, 124F, 124H, 124L; Annex II p.94
"""

from __future__ import annotations

from typing import Any

import polars as pl
import pytest

from rwa_calc.contracts.edges import LOAN_SPLIT_CARRIERS
from rwa_calc.reporting.cellspec import (
    CellSpec,
    Count,
    Formula,
    RowPredicate,
    SafeSum,
    SideContext,
    Sum,
    TemplateSpec,
)
from rwa_calc.reporting.kernel.rw_parts import (
    RW_PART_COL,
    has_two_part_rows,
    split_risk_weight_parts,
    summed_columns,
)

_EXPOSURE_COLS = ("ead_final", "reporting_gross_on_bs")
_RWEA_COLS = ("rwa_final",)

#: RP-LN-RRE of the rich portfolio: 400,000 at 60% LTV to a natural person.
_SHARE = 0.55 / 0.60
_BLEND = 0.20 * _SHARE + 0.75 * (1.0 - _SHARE)


def _row(reference: str, **overrides: Any) -> dict[str, Any]:
    row: dict[str, Any] = {
        "exposure_reference": reference,
        "ead_final": 400_000.0,
        "reporting_gross_on_bs": 400_000.0,
        "rwa_final": 400_000.0 * _BLEND,
        "risk_weight": _BLEND,
        "sa_loan_split_secured_share": _SHARE,
        "sa_loan_split_secured_rw": 0.20,
        "sa_loan_split_residual_rw": 0.75,
    }
    row.update(overrides)
    return row


def _frame(*rows: dict[str, Any]) -> pl.DataFrame:
    return pl.DataFrame(
        list(rows),
        schema_overrides=dict.fromkeys(LOAN_SPLIT_CARRIERS, pl.Float64),
    )


def _split(frame: pl.DataFrame) -> pl.DataFrame:
    return split_risk_weight_parts(frame, exposure_cols=_EXPOSURE_COLS, rwea_cols=_RWEA_COLS)


def test_a_two_part_row_becomes_its_secured_and_residual_parts() -> None:
    parts = _split(_frame(_row("RRE")))

    assert parts[RW_PART_COL].to_list() == ["secured", "residual"]
    assert parts["risk_weight"].to_list() == [0.20, 0.75]
    assert parts["ead_final"].to_list() == pytest.approx([366_666.666667, 33_333.333333])
    assert parts["rwa_final"].to_list() == pytest.approx([73_333.333333, 25_000.0])


@pytest.mark.parametrize("column", [*_EXPOSURE_COLS, *_RWEA_COLS])
def test_the_parts_sum_to_the_row(column: str) -> None:
    whole = _frame(_row("RRE"))

    parts = _split(whole)

    assert parts[column].sum() == pytest.approx(whole[column].sum(), rel=1e-15)


def test_each_parts_rwea_is_its_exposure_at_its_own_weight() -> None:
    """Without a multiplier the RWEA of a part is exactly exposure x part weight."""
    parts = _split(_frame(_row("RRE")))

    for row in parts.iter_rows(named=True):
        assert row["rwa_final"] == pytest.approx(row["ead_final"] * row["risk_weight"])


def test_rows_that_are_not_two_part_keep_their_place_and_values() -> None:
    plain = _row(
        "CORP",
        risk_weight=1.0,
        rwa_final=400_000.0,
        sa_loan_split_secured_share=None,
        sa_loan_split_secured_rw=None,
        sa_loan_split_residual_rw=None,
    )

    parts = _split(_frame(plain, _row("RRE")))

    assert parts["exposure_reference"].to_list() == ["CORP", "RRE", "RRE"]
    assert parts.row(0, named=True) | {RW_PART_COL: None} == plain | {RW_PART_COL: None}


@pytest.mark.parametrize(
    ("reference", "moved_weight"),
    [
        # Art. 127: a defaulted mortgage takes 100% on the whole exposure.
        ("RRE-DEFAULTED", 1.0),
        # Art. 235: a guaranteed leg at an institution guarantor's 50%.
        ("RRE__G_INST", 0.5),
        # Art. 235: a guaranteed leg at a sovereign guarantor's 0%.
        ("RRE__G_CGCB", 0.0),
    ],
)
def test_a_row_whose_weight_has_moved_since_stays_whole(
    reference: str, moved_weight: float
) -> None:
    """A later step re-weighted the row: its carriers are stale, so it is not split.

    The dispatcher writes the carriers; Art. 127 and CRM substitution run after it
    and leave them on the row. Only the blend-equality check tells a stale carrier
    from a live one — the non-zero weights are what pin it, since a 0% weight is
    also refused by the separate ``weight > 0`` gate.
    """
    moved = _frame(_row(reference, risk_weight=moved_weight, rwa_final=400_000.0 * moved_weight))

    assert _split(moved).to_dicts() == moved.to_dicts()


@pytest.mark.parametrize("share", [1.0, 0.0])
def test_a_row_with_no_second_part_stays_whole(share: float) -> None:
    """The kernel's own ``0 < share < 1`` gate: a share of 1 (or 0) is one part, not two.

    The engine never writes such a carrier; this pins the kernel's gate on its own, so
    dropping it alone reddens here rather than only in the end-to-end control.
    """
    weight = 0.20 * share + 0.75 * (1.0 - share)
    whole = _frame(
        _row(
            "RRE-ONE-PART",
            risk_weight=weight,
            rwa_final=400_000.0 * weight,
            sa_loan_split_secured_share=share,
        )
    )

    assert _split(whole).equals(whole)


def test_a_currency_mismatch_row_is_split_on_its_pre_multiplier_weight() -> None:
    """Art. 123B: banded on the un-multiplied parts; the RWEA keeps the 1.5x."""
    multiplied = _BLEND * 1.5
    row = _row(
        "RRE-FX",
        risk_weight=multiplied,
        rwa_final=400_000.0 * multiplied,
        currency_mismatch_multiplier_applied=True,
        risk_weight_pre_currency_mismatch=_BLEND,
    )

    parts = _split(_frame(row))

    assert parts["risk_weight"].to_list() == [0.20, 0.75]
    assert parts["risk_weight_pre_currency_mismatch"].to_list() == [0.20, 0.75]
    assert parts["rwa_final"].sum() == pytest.approx(400_000.0 * multiplied, rel=1e-15)
    assert parts["rwa_final"].to_list() == pytest.approx(
        [366_666.666667 * 0.20 * 1.5, 33_333.333333 * 0.75 * 1.5]
    )


def test_a_mismatch_flag_without_the_multiplier_reads_the_applied_weight() -> None:
    """Flag False: the snapshot equals the applied weight; the row is split on it."""
    row = _row(
        "RRE-GBP",
        currency_mismatch_multiplier_applied=False,
        risk_weight_pre_currency_mismatch=_BLEND,
    )

    assert _split(_frame(row))[RW_PART_COL].to_list() == ["secured", "residual"]


#: An institution guarantor's 20%, below the loan's own blended weight: Art. 235 applies.
_PROVIDER_RW = 0.20


def _covered(reference: str, **overrides: Any) -> dict[str, Any]:
    """A beneficially substituted covered leg: the provider's weight, the obligor's blend kept."""
    return (
        _row(
            reference,
            risk_weight=_PROVIDER_RW,
            rwa_final=400_000.0 * _PROVIDER_RW,
            pre_crm_risk_weight=_BLEND,
            is_guarantee_beneficial=True,
        )
        | overrides
    )


def test_a_substituted_row_is_split_on_the_obligors_own_weight() -> None:
    """The covered part's ORIGINAL exposure is the obligor's, so it is reported in the two
    parts of the obligor's own (pre-substitution) weight: the part weights go to
    ``pre_crm_risk_weight``, while ``risk_weight`` keeps the provider's weight on both."""
    parts = _split(_frame(_covered("RRE__G_INST")))

    assert parts[RW_PART_COL].to_list() == ["secured", "residual"]
    assert parts["pre_crm_risk_weight"].to_list() == [0.20, 0.75]
    assert parts["risk_weight"].to_list() == [_PROVIDER_RW, _PROVIDER_RW]


def test_a_substituted_rows_rwea_is_split_with_its_exposure() -> None:
    """Both parts are at the provider's weight, so each takes its exposure share of the RWEA."""
    parts = _split(_frame(_covered("RRE__G_INST")))
    assert parts.height == 2, "the row was not split - this test would prove nothing"

    assert parts["rwa_final"].sum() == pytest.approx(400_000.0 * _PROVIDER_RW, rel=1e-15)
    for row in parts.iter_rows(named=True):
        assert row["rwa_final"] == pytest.approx(row["ead_final"] * _PROVIDER_RW)


@pytest.mark.parametrize(
    ("case", "overrides"),
    [
        # Art. 127 re-weighted the obligor first: its own weight is no longer the blend.
        ("stale-own-weight", {"pre_crm_risk_weight": 1.0}),
        # An unknown benefit is not a substitution (null-safe), and the provider's
        # weight is not the blend either.
        ("unknown-benefit", {"is_guarantee_beneficial": None}),
        ("declined", {"is_guarantee_beneficial": False}),
    ],
)
def test_a_covered_row_that_is_not_split_on_its_own_weight_stays_whole(
    case: str, overrides: dict[str, Any]
) -> None:
    covered = _frame(_covered("RRE__G_INST", **overrides))

    assert _split(covered).equals(covered), case
    assert not has_two_part_rows(covered), case


def test_null_carriers_are_a_no_op() -> None:
    nulls = _frame(
        _row(
            "RRE-50",
            sa_loan_split_secured_share=None,
            sa_loan_split_secured_rw=None,
            sa_loan_split_residual_rw=None,
        )
    )

    assert _split(nulls).equals(nulls)


def test_a_frame_without_the_carriers_is_returned_unchanged() -> None:
    """ABSENT, not null (LESSONS B1): a CRR ledger never carries these columns."""
    absent = _frame(_row("RRE")).drop(LOAN_SPLIT_CARRIERS)
    assert not set(LOAN_SPLIT_CARRIERS) & set(absent.columns)

    assert _split(absent) is absent


@pytest.mark.parametrize(
    ("case", "frame", "expected"),
    [
        ("two-part", _frame(_row("RRE")), True),
        ("stale", _frame(_row("RRE-DEFAULTED", risk_weight=1.0, rwa_final=400_000.0)), False),
        ("null", _frame(_row("RRE-50", sa_loan_split_secured_share=None)), False),
        ("absent", _frame(_row("CRR")).drop(LOAN_SPLIT_CARRIERS), False),
        ("substituted", _frame(_covered("RRE__G_INST")), True),
    ],
)
def test_has_two_part_rows_agrees_with_the_split(
    case: str, frame: pl.DataFrame, *, expected: bool
) -> None:
    """The gate a template reads before resolving what to split, on the split's own rule."""
    assert has_two_part_rows(frame) is expected, case
    assert (_split(frame).height > frame.height) is expected, case


def test_a_column_cannot_be_both_an_exposure_and_an_rwea() -> None:
    with pytest.raises(ValueError, match="rwa_final"):
        split_risk_weight_parts(
            _frame(_row("RRE")), exposure_cols=("rwa_final",), rwea_cols=("rwa_final",)
        )


def test_summed_columns_reads_every_summing_binding_of_a_spec() -> None:
    spec = _spec(
        {
            ("0010", "0010"): CellSpec(SafeSum(("gross_on", "gross_off"))),
            ("0010", "0200"): CellSpec(Sum("ead_final")),
            ("0010", "0220"): CellSpec(Sum("rwa_final"), predicate=RowPredicate()),
            ("0010", "0040"): CellSpec(Formula(refs=("0010",), fn=lambda cells, _p: 0.0)),
            ("0010", "0100"): CellSpec(SideContext("substitution_inflow")),
        }
    )

    assert summed_columns(spec) == {"gross_on", "gross_off", "ead_final", "rwa_final"}


def test_summed_columns_refuses_a_binding_a_split_would_change() -> None:
    """A Count over split rows would double; the helper refuses rather than miscount."""
    spec = _spec({("0010", "0010"): CellSpec(Count("exposure_reference"))})

    with pytest.raises(ValueError, match="Count"):
        summed_columns(spec)


def _spec(cells: dict[tuple[str, str], CellSpec]) -> TemplateSpec:
    return TemplateSpec(name="t", rows=(), column_refs=(), cells=cells)
