"""
Unit tests: the Basel 3.1 Art. 124H(3) cap reads the whole of Art. 124I,
including the Art. 124I(3) junior-charge weights (review CL-10).

Pipeline position:
    CRMProcessor -> RealEstateSplitter -> SACalculator
    (engine/sa/b31_risk_weight_tables.py::b31_commercial_rw_expr,
    ::lookup_b31_commercial_rw)

Key responsibility: a regulatory commercial real-estate exposure to a
counterparty that is neither a natural person nor an SME, not materially
dependent on the property, takes max(60%, min(counterparty weight, the weight
Art. 124I would assign)). Where charges not held by the institution rank ahead,
"the risk weight that would be assigned to the exposure under Article 124I" is
the Art. 124I(3) junior weight — 100% / 125% / 137.5% by LTV — not the
Art. 124I(1)/(2) base table the cap used before. It binds only where the
counterparty weight exceeds that weight (CQS 5-6 corporates, 150%).

Rule text (verbatim, PS1/26 Appendix 1):
- Art. 124H(3): "An institution shall, to the entirety of a regulatory
  commercial real estate exposure that is not to a natural person or an SME and
  that is not materially dependent on the cash-flows generated by the property,
  assign a risk weight that is the higher of: (a) 60%; and (b) the lower of:
  (i) the risk weight of the counterparty in accordance with point (e) of
  Article 124L(1); and (ii) the risk weight that would be assigned to the
  exposure under Article 124I if the exposure was materially dependent on the
  cash-flows generated by the property."
- Art. 124I(3): "Where a commercial real estate exposure is materially dependent
  on cash-flows generated by the property and there are charges not held by the
  institution that rank in priority ahead of the charge that the exposure is
  secured by, an institution shall assign a risk weight of: (a) 100% to the
  whole of the exposure if the LTV is less than or equal to 60%; (b) 125% to the
  whole of the exposure if the LTV is greater than 60% and less than or equal to
  80%; or (c) 137.5% to the whole of the exposure if the LTV is greater than 80%."

References:
- PS1/26 Art. 124H(3), 124I(1)-(3), 124L(1)(e)
"""

from __future__ import annotations

from datetime import date
from decimal import Decimal

import pytest

from rwa_calc.contracts.config import CalculationConfig
from rwa_calc.engine.sa import SACalculator
from rwa_calc.engine.sa.b31_risk_weight_tables import lookup_b31_commercial_rw
from tests.fixtures.single_exposure import calculate_single_sa_exposure


@pytest.fixture
def sa_calculator() -> SACalculator:
    return SACalculator()


def _rw(sa_calculator: SACalculator, *, cqs: int | None, ltv: str, prior: str) -> float:
    result = calculate_single_sa_exposure(
        sa_calculator,
        ead=Decimal("70000"),
        config=CalculationConfig.basel_3_1(reporting_date=date(2027, 3, 31)),
        exposure_class="commercial_mortgage",
        property_type="commercial",
        cqs=cqs,
        ltv=Decimal(ltv),
        prior_charge_ltv=Decimal(prior),
        has_income_cover=False,
        qualifies_as_retail=False,
    )
    return float(result["risk_weight"])


class TestArt124h3CapReadsArt124i3:
    @pytest.mark.parametrize(
        ("ltv", "expected_rw", "pre_fix_rw"),
        [
            # CQS 5 corporate, 150%. Prior charge 0.2 ahead of ours.
            ("0.90", 1.375, 1.10),  # 124I(3)(c); pre-fix base 124I(2) 110%
            ("0.70", 1.25, 1.00),  # 124I(3)(b); pre-fix base 124I(1) 100%
            ("0.50", 1.00, 1.00),  # 124I(3)(a) equals the base weight
        ],
    )
    def test_junior_charge_cap_takes_the_art_124i_3_weight(
        self, sa_calculator: SACalculator, ltv: str, expected_rw: float, pre_fix_rw: float
    ) -> None:
        # Act
        rw = _rw(sa_calculator, cqs=5, ltv=ltv, prior="0.20")

        # Assert
        assert rw == pytest.approx(expected_rw)

    def test_no_prior_charge_keeps_the_base_table(self, sa_calculator: SACalculator) -> None:
        """Control: no charge ahead -> Art. 124I(2) 110% at LTV 0.9."""
        # Act
        rw = _rw(sa_calculator, cqs=5, ltv="0.90", prior="0.0")

        # Assert
        assert rw == pytest.approx(1.10)

    def test_counterparty_weight_below_the_cap_still_binds(
        self, sa_calculator: SACalculator
    ) -> None:
        """Unrated corporate (100%): min(100%, 137.5%) = 100% — the blast-radius bound."""
        # Act
        rw = _rw(sa_calculator, cqs=None, ltv="0.90", prior="0.20")

        # Assert
        assert rw == pytest.approx(1.00)


class TestScalarLookupAgrees:
    def test_scalar_lookup_applies_the_junior_weight(self) -> None:
        # Act
        rw, desc = lookup_b31_commercial_rw(
            Decimal("0.90"),
            counterparty_rw=Decimal("1.50"),
            is_income_producing=False,
            is_natural_person_or_sme=False,
            prior_charge_ltv=Decimal("0.20"),
        )

        # Assert
        assert rw == Decimal("1.375")
        assert "Art. 124H(3)" in desc
